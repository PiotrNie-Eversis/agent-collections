// Pins source text only: it reads the file and does not watch runtime behaviour.
// It would miss a dynamic import or a network module outside this list. The
// import check is backed by every test here, because a value import from Pi
// would not resolve when this file loads the asset.
test("source: Pi import is type-only, Node stdlib otherwise, no shell or network", () => {
  const source = fs.readFileSync(ASSET, "utf8");
  const imports = [...source.matchAll(/^import\s+(type\s+)?[\s\S]*?\sfrom\s+"([^"]+)";$/gm)];
  assert.ok(imports.length > 0);
  for (const [statement, typeOnly, from] of imports) {
    if (from.startsWith("node:")) continue;
    assert.equal(from, "@earendil-works/pi-coding-agent", statement);
    assert.ok(typeOnly, `value import from Pi: ${statement}`);
  }
  assert.doesNotMatch(source, /child_process|node:net|node:http|node:https|\bfetch\(/);
});

/** Every path under dir with what it holds; a symlink counts as its link text. */
function snapshot(dir) {
  const entries = {};
  for (const entry of fs.readdirSync(dir, { recursive: true, withFileTypes: true })) {
    const abs = path.join(entry.parentPath, entry.name);
    const rel = path.relative(dir, abs);
    if (entry.isSymbolicLink()) entries[rel] = `link:${fs.readlinkSync(abs)}`;
    else if (entry.isFile()) entries[rel] = fs.readFileSync(abs, "utf8");
    else entries[rel] = "dir";
  }
  return entries;
}

function changedPaths(before, after) {
  return [...new Set([...Object.keys(before), ...Object.keys(after)])]
    .filter((rel) => before[rel] !== after[rel])
    .sort();
}

/** One save of a plan, then a new session after its boxes are closed, which clears the pointer. */
function runSaveAndClear(root) {
  const ext = load(root);
  toolResult(ext, fakeCtx({ root }), "write", PLAN);
  fs.writeFileSync(path.join(root, PLAN), "- [x] done\n");
  start(load(root), fakeCtx({ root }));
}

test("a save and a clear change nothing outside the state folder, even through symlinks", () => {
  const STATE_REL = path.join(".pi", "eversis-state");
  const sandbox = () => {
    const root = project();
    writeFile(root, PLAN, "- [ ] open\n");
    const outside = mkTmp();
    writeFile(outside, ".gitignore", "kept\n");
    writeFile(outside, "active-plan.json", "kept\n");
    return { root, outside };
  };

  const plain = sandbox();
  const before = snapshot(plain.root);
  runSaveAndClear(plain.root);
  const changed = changedPaths(before, snapshot(plain.root)).filter((rel) => rel !== PLAN);
  assert.ok(changed.length > 0, "the save left the state folder in place");
  for (const rel of changed) assert.ok(rel.startsWith(`${STATE_REL}${path.sep}`) || rel === STATE_REL, rel);

  for (const hostile of [
    ({ root, outside }) => {
      fs.symlinkSync(outside, path.join(root, ".pi", "eversis-state"));
    },
    ({ root, outside }) => {
      fs.mkdirSync(path.join(root, ".pi", "eversis-state"));
      fs.symlinkSync(path.join(outside, ".gitignore"), path.join(root, ".pi", "eversis-state", ".gitignore"));
      fs.symlinkSync(path.join(outside, "active-plan.json"), path.join(root, POINTER_REL));
    },
    ({ root, outside }) => {
      fs.renameSync(path.join(root, ".pi"), path.join(outside, "moved-pi"));
      fs.symlinkSync(path.join(outside, "moved-pi"), path.join(root, ".pi"));
    },
  ]) {
    const paths = sandbox();
    hostile(paths);
    const outsideBefore = snapshot(paths.outside);
    runSaveAndClear(paths.root);
    assert.deepEqual(snapshot(paths.outside), outsideBefore);
  }
});
