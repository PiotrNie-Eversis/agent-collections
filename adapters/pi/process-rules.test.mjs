  const stateDir = path.join(root, ".pi", "eversis-state");
  fs.mkdirSync(stateDir);
  const gitignoreTarget = writeFile(mkTmp(), "precious.txt", "precious\n");
  const pointerTarget = writeFile(mkTmp(), "other.json", "other\n");
  fs.symlinkSync(gitignoreTarget, path.join(stateDir, ".gitignore"));
