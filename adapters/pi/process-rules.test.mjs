test("command: active in the same run with full listing, persisted once, stays on later runs", () => {
  const root = project();
  const ext = load(root);
  const ctx = fakeCtx({ root });
  start(ext, ctx);
  assert.deepEqual(input(ext, ctx, "/eversis-implement AC-1"), { action: "continue" });

  const first = beforeRun(ext, ctx);
  const section = first.systemPromptOptions.sections[SECTION_KEY];
  assert.ok(section.startsWith(NAMING_LINE));
  assert.ok(section.includes("# Body of eversis-rule-one"));
  assert.ok(section.includes("# Body of eversis-rule-two"));
  assert.ok(!section.includes("GENERATED"));
  assert.ok(!section.includes('description: "d"'));
  assert.equal(first.systemPromptOptions.skills.length, 2, "full listing");

  input(ext, ctx, "a plain follow-up");
  input(ext, ctx, "/eversis-review AC-1");
  const later = beforeRun(ext, ctx);
  assert.ok(later.systemPromptOptions.sections[SECTION_KEY], "added again on a later run");
  assert.equal(later.systemPromptOptions.skills.length, 2);

  assert.deepEqual(ext.appended, [
    { type: "custom", customType: ENTRY_TYPE, data: { trigger: "/eversis-implement" } },
  ]);
  assert.equal(ctx.notices.length, 1);
  assert.match(ctx.notices[0].message, /\/eversis-implement/);
  assert.doesNotMatch(ctx.notices[0].message, /next run/);
});

