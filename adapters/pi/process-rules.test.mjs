const tmpDirs = [];
function mkTmp() {
  // Real path, so the tests that add a symlink control the only difference.
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "pi-adapter-test-")));
  tmpDirs.push(dir);
  return dir;
}
after(() => {
  for (const dir of tmpDirs) fs.rmSync(dir, { recursive: true, force: true });
});

function writeFile(root, rel, text) {
  const abs = path.join(root, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, text);
  return abs;
}

function skillFile(id) {
  return `---\nname: "${id}"\ndescription: "d"\n---\n\n<!-- GENERATED by adapters/pi/generate.mjs — do not edit; re-run the generator -->\n\n# Body of ${id}\n`;
}

/** Temp project with the two bundle skills. */
function project(skillIds = SKILL_IDS) {
  const root = mkTmp();
  for (const id of skillIds) writeFile(root, `.pi/skills/${id}/SKILL.md`, skillFile(id));
  return root;
}

function listFiles(root) {
  return fs
    .readdirSync(root, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => path.relative(root, path.join(entry.parentPath, entry.name)))
    .sort();
}

/** Fake Pi plus a loaded extension for one test. */
function load(root, { commands = COMMANDS, home = mkTmp(), skillIds = SKILL_IDS } = {}) {
  const handlers = {};
  const appended = [];
  const pi = {
    on: (name, handler) => {
      handlers[name] = handler;
    },
    getCommands: () => commands,
    appendEntry: (customType, data) => appended.push({ type: "custom", customType, data }),
  };
  register(pi, { skillIds, root, home });
  return { handlers, appended, home };
}

function fakeCtx({ root, cwd = root, idle = true, branch = [], hasUI = true } = {}) {
  const notices = [];
  return {
    notices,
    cwd,
    hasUI,
    ui: { notify: (message, type) => notices.push({ message, type }) },
    isIdle: () => idle,
    sessionManager: { getBranch: () => branch },
  };
}

function runOptions(skills = [{ name: "eversis-review" }, { name: "team-skill" }]) {
  return { systemPromptOptions: { sections: {}, skills } };
}

const start = (ext, ctx, reason = "startup") => ext.handlers.session_start({ reason }, ctx);
const input = (ext, ctx, text, extra = {}) => ext.handlers.input({ text, ...extra }, ctx);
const beforeRun = (ext, ctx, event = runOptions()) => {
  ext.handlers.before_agent_start(event, ctx);
  return event;
};
const toolResult = (ext, ctx, toolName, toolPath, isError = false) =>
  ext.handlers.tool_result({ toolName, input: { path: toolPath }, isError }, ctx);

