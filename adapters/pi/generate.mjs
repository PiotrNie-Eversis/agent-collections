function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function findRepoRoot(startDir) {
  let dir = startDir;
  for (;;) {
    if (
      fs.existsSync(path.join(dir, ".ai")) &&
      fs.existsSync(path.join(dir, "adapters"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      fail(
        "could not find repository root (expected .ai/ and adapters/). Run from repo root.",
      );
    }
    dir = parent;
  }
}

// Same permissive check as adapters/claude/generate-commands.mjs — the prefix
// may be a literal env-var token (${AGENT_COLLECTIONS_HOME}) in local vendor
// mode, not always a real path.
function assertSafeFrameworkPrefix(value) {
  if (value.startsWith("/")) {
    fail(`--framework-prefix must not be an absolute path: ${value}`);
  }
  if (value.split("/").some((segment) => segment === "..")) {
    fail(`--framework-prefix must not escape the target root: ${value}`);
  }
  return value.replace(/\/+$/, "");
}

function parseArgs(argv) {
  let outRoot = null;
  let frameworkPrefix = "";
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--out requires a directory path");
      }
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    if (arg === "--framework-prefix") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--framework-prefix requires a value");
      }
      frameworkPrefix = assertSafeFrameworkPrefix(next);
      i++;
      continue;
    }
    if (arg === "--check") {
      check = true;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: node adapters/pi/generate.mjs [--out <dir>] [--framework-prefix <path>] [--check]\n" +
          "  Default: write .pi/ (repo-relative).\n" +
          "  --out: write under <dir>, preserving the .pi/… tail.\n" +
          "  --framework-prefix: prepend <path> to SSOT pointers (see\n" +
          "    adapters/claude/generate.mjs). Empty = self-host.\n" +
          "  --check: no writes; exit 1 and list each drifted, missing or orphan\n" +
          "    generated file (.pi/settings.json is consumer-owned and not checked).",
      );
      process.exit(0);
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot, frameworkPrefix, check };
}

function stripQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function parseScalar(raw) {
  const value = raw.trim();
  if (value === "true") return true;
  if (value === "false") return false;
  if (value === "[]") return [];
  if (/^-?\d+$/.test(value)) return Number(value);
  if (value.length >= 2 && value.startsWith('"') && value.endsWith('"')) {
    try {
      return JSON.parse(value);
    } catch {
      return stripQuotes(value);
    }
  }
  return stripQuotes(value);
}

/**
 * Constrained YAML parser for the Pi rule-map shape: version + rules list of
 * items with scalar fields (same grammar as adapters/sync.mjs parseRuleMapYaml).
 */
function parseRuleMapYaml(text) {
  const lines = text.split(/\r?\n/);
  const doc = { version: null, rules: [] };
  let currentRule = null;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.replace(/\s+#.*$/, "");
    if (!line.trim() || line.trim().startsWith("#")) continue;

    const indent = line.match(/^ */)[0].length;
    const trimmed = line.trim();

    if (indent === 0 && trimmed.startsWith("version:")) {
      doc.version = parseScalar(trimmed.slice("version:".length));
      continue;
    }
    if (indent === 0 && trimmed === "rules:") {
      continue;
    }
    if (indent === 2 && trimmed.startsWith("- ")) {
      currentRule = {};
      doc.rules.push(currentRule);
      const rest = trimmed.slice(2).trim();
      if (rest.includes(":")) {
        const idx = rest.indexOf(":");
        const val = rest.slice(idx + 1).trim();
        if (val !== "") currentRule[rest.slice(0, idx).trim()] = parseScalar(val);
      }
      continue;
    }
    if (currentRule && indent === 4 && trimmed.includes(":")) {
      const idx = trimmed.indexOf(":");
      currentRule[trimmed.slice(0, idx).trim()] = parseScalar(
        trimmed.slice(idx + 1),
      );
      continue;
    }
    fail(`Pi rule-map: unexpected line ${i + 1}: ${rawLine}`);
  }
  return doc;
}

/**
 * Minimal deny-list parser: version + deny: [] or deny: with "- id" items.
 * Identical grammar to adapters/claude/command-deny.yaml (reused, not duplicated).
 */
function parseCommandDenyYaml(text) {
  const lines = text.split(/\r?\n/);
  const doc = { version: null, deny: [] };
  let inDeny = false;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.replace(/\s+#.*$/, "");
    if (!line.trim() || line.trim().startsWith("#")) continue;

    const indent = line.match(/^ */)[0].length;
    const trimmed = line.trim();

    if (indent === 0 && trimmed.startsWith("version:")) {
      doc.version = parseScalar(trimmed.slice("version:".length));
      inDeny = false;
      continue;
    }
    if (indent === 0 && trimmed.startsWith("deny:")) {
      const inline = trimmed.slice("deny:".length).trim();
      if (inline === "[]") {
        doc.deny = [];
        inDeny = false;
      } else if (inline === "") {
        doc.deny = [];
        inDeny = true;
      } else {
        fail(`command-deny.yaml: unsupported inline deny value at line ${i + 1}`);
      }
      continue;
    }
    if (inDeny && indent >= 2 && trimmed.startsWith("- ")) {
      doc.deny.push(String(parseScalar(trimmed.slice(2).trim())));
      continue;
    }
    fail(`command-deny.yaml: unexpected line ${i + 1}: ${rawLine}`);
  }
  return doc;
}

function loadCommandDeny() {
  if (!fs.existsSync(DENY_PATH)) {
    return new Set();
  }
  const doc = parseCommandDenyYaml(fs.readFileSync(DENY_PATH, "utf8"));
  if (doc.version !== 1) {
    fail(`unsupported command-deny version: ${doc.version} (expected 1)`);
  }
  return new Set(doc.deny.map(String));
}

function readFileOrFail(abs, label) {
  if (!fs.existsSync(abs)) fail(`missing ${label}: ${abs}`);
  return fs.readFileSync(abs, "utf8").replace(/^﻿/, "");
}

function normalizeNewlines(text) {
  return text.replace(/^﻿/, "").replace(/\r\n/g, "\n");
}

function listFrameworkSkillNames(repoRoot) {
  const skillsRoot = path.join(repoRoot, ".ai", "skills");
  if (!fs.existsSync(skillsRoot)) return new Set();
  return new Set(
    fs
      .readdirSync(skillsRoot, { withFileTypes: true })
      .filter((e) => e.isDirectory() && e.name.startsWith("eversis-"))
      .map((e) => e.name),
  );
}

function loadRuleMap(repoRoot) {
  const map = parseRuleMapYaml(readFileOrFail(MAP_PATH, "Pi rule map"));
  if (map.version !== 1) {
    fail(`Pi rule-map: unsupported version ${map.version} (expected 1)`);
  }
  if (map.rules.length === 0) {
    fail("Pi rule-map has no rules");
  }
  const frameworkSkills = listFrameworkSkillNames(repoRoot);
  const seenSkillIds = new Set();
  for (const rule of map.rules) {
    if (!rule.id || !rule.source) {
      fail(`Pi rule-map entry missing id/source: ${JSON.stringify(rule)}`);
    }
    if (!["append_system", "skill", "none"].includes(rule.target)) {
      fail(`Pi rule-map ${rule.id}: unknown target ${rule.target}`);
    }
    if (rule.target === "skill") {
      const skillId = rule.skill_id;
      if (!skillId || !String(skillId).startsWith(ROLE_SKILL_PREFIX)) {
        fail(`Pi rule-map ${rule.id}: skill_id must start with ${ROLE_SKILL_PREFIX}`);
      }
      if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(skillId)) {
        fail(`Pi rule-map ${rule.id}: invalid skill name ${skillId}`);
      }
      if (skillId.length > MAX_SKILL_NAME) {
        fail(`Pi rule-map ${rule.id}: skill name exceeds ${MAX_SKILL_NAME} chars (${skillId.length})`);
      }
      if (frameworkSkills.has(skillId)) {
        fail(`Pi rule-map ${rule.id}: skill id ${skillId} collides with .ai/skills/${skillId}`);
      }
      if (seenSkillIds.has(skillId)) {
        fail(`Pi rule-map ${rule.id}: duplicate skill id ${skillId}`);
      }
      seenSkillIds.add(skillId);
      const description = typeof rule.description === "string" ? rule.description.trim() : "";
      if (!description) {
        fail(`Pi rule-map ${rule.id}: description is required for target skill`);
      }
      if (description.length > MAX_SKILL_DESCRIPTION) {
        fail(`Pi rule-map ${rule.id}: description exceeds ${MAX_SKILL_DESCRIPTION} chars (${description.length})`);
      }
    }
    if (rule.target === "none" && rule.skill_id && !frameworkSkills.has(rule.skill_id)) {
      fail(`Pi rule-map ${rule.id}: serving framework skill .ai/skills/${rule.skill_id} not found`);
    }
  }
  return map;
}

/** Remove a leading YAML front-matter block and any GENERATED marker, return the body. */
function stripFrontMatterAndMarker(text) {
  let body = normalizeNewlines(text);
  const fm = body.match(/^---\n[\s\S]*?\n---\n?/);
  if (fm) body = body.slice(fm[0].length);
  body = body.replace(/<!--\s*GENERATED[^>]*-->\n?/gi, "");
  return body.replace(/^\s+/, "").replace(/\s+$/, "");
}

/** Read a front-matter scalar value by key (e.g. prompt_description). */
function frontMatterValue(text, key) {
  const fm = normalizeNewlines(text).match(/^---\n([\s\S]*?)\n---/);
  if (!fm) return null;
  const m = fm[1].match(new RegExp(`^${key}:\\s*(.*)$`, "m"));
  if (!m) return null;
  const value = String(parseScalar(m[1]));
  return value.trim() || null;
}

/** First non-heading, non-admonition prose line of a body (description fallback). */
function firstUsableLine(body) {
  for (const raw of body.split("\n")) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || line.startsWith(":::") || line.startsWith("<!--")) {
      continue;
    }
    return line;
  }
  return null;
}

/**
 * Replace "$" with "＄" (U+FF04) wherever it would start a Pi prompt-template
 * substitution ($<digit>, $@, $ARGUMENTS, ${…}); see Pi
 * dist/core/prompt-templates.js substituteArgs. Pi has no escape syntax.
 */
function neutralizePiSubstitution(text) {
  return text.replace(/\$(?=\d|@|ARGUMENTS|\{)/g, "＄");
}

/** Front-matter block with every value emitted as a JSON-quoted string. */
function buildFrontMatter(entries) {
  return [
    "---",
    ...entries.map(([key, value]) => `${key}: ${JSON.stringify(String(value))}`),
    "---",
  ].join("\n");
}

function ssotPath(frameworkPrefix, rel) {
  return frameworkPrefix ? `${frameworkPrefix}/${rel}` : rel;
}

function discoverPrompts(repoRoot, deny) {
  /** @type {{ id: string, sourceRel: string, audience: string }[]} */
  const found = [];
  const seen = new Set();
  for (const audience of PROMPT_BUCKETS) {
    const dirAbs = path.join(repoRoot, ".ai", "prompts", audience);
    if (!fs.existsSync(dirAbs)) continue;
    for (const name of fs.readdirSync(dirAbs).sort()) {
      if (!/^eversis-.*\.md$/.test(name)) continue;
      const id = name.replace(/\.md$/, "");
      if (deny.has(id)) continue;
      if (seen.has(id)) fail(`duplicate prompt id across buckets: ${id}`);
      seen.add(id);
      found.push({
        id,
        sourceRel: path.posix.join(".ai/prompts", audience, name),
        audience,
      });
    }
  }
  found.sort((a, b) => a.id.localeCompare(b.id));
  return found;
}

function buildPromptContent(prompt, raw, frameworkPrefix) {
  const body = stripFrontMatterAndMarker(raw);
  const description =
    frontMatterValue(raw, "prompt_description") || firstUsableLine(body);
  if (!description) {
    fail(
      `prompt ${prompt.sourceRel} has no prompt_description and no usable first line — add prompt_description to the SSOT`,
    );
  }

  // Executable section through end of body (benchmark behaviour); whole body
  // when the SSOT has no "## Executable prompt" heading.
  const match = EXECUTABLE_HEADING_RE.exec(body);
  const executable = match
    ? body.slice(match.index).replace(EXECUTABLE_HEADING_RE, "## Executable prompt")
    : body;

  return [
    buildFrontMatter([
      ["description", description],
      ["argument-hint", PROMPT_ARGUMENT_HINT],
    ]),
    "",
    GENERATED_MARKER,
    "",
    `> SSOT: \`${ssotPath(frameworkPrefix, prompt.sourceRel)}\` — Agent Collections prompt \`${prompt.id}\` (${prompt.audience}). Edit the SSOT, not this file.`,
    "",
    neutralizePiSubstitution(executable.trim()),
    "",
    "---",
    "",
    USER_INPUT_LINE,
    "",
  ].join("\n");
}

function buildRoleSkillContent(rule, repoRoot, frameworkPrefix) {
  const body = stripFrontMatterAndMarker(
    readFileOrFail(path.join(repoRoot, rule.source), `rule source for ${rule.id}`),
  );
  return [
    buildFrontMatter([
      ["name", rule.skill_id],
      ["description", rule.description.trim()],
    ]),
    "",
    GENERATED_MARKER,
    "",
    `> Agent Collections role rule \`${rule.id}\` — SSOT: \`${ssotPath(frameworkPrefix, rule.source)}\`. Edit the SSOT, not this file.`,
    "",
    body,
    "",
  ].join("\n");
}

/**
 * Decide whether the consumer's project-stack rule is appended to APPEND_SYSTEM.md.
 * Skipped when absent, byte-identical to the framework template (after newline
 * normalisation), or still carrying a template placeholder marker.
 * @returns {string|null} body to append, or null
 */
function resolveStackOverlay(repoRoot, targetRoot) {
  const overlayAbs = path.join(targetRoot, STACK_OVERLAY_REL);
  if (!fs.existsSync(overlayAbs)) {
    console.log(
      `pi adapter: project-stack overlay skipped (${STACK_OVERLAY_REL} not found)`,
    );
    return null;
  }
  const overlay = normalizeNewlines(fs.readFileSync(overlayAbs, "utf8"));
  const templateAbs = path.join(repoRoot, STACK_TEMPLATE_REL);
  const template = fs.existsSync(templateAbs)
    ? normalizeNewlines(fs.readFileSync(templateAbs, "utf8"))
    : null;
  const unmodified =
    (template !== null && overlay === template) ||
    STACK_PLACEHOLDER_MARKERS.some((marker) => overlay.includes(marker));
  if (unmodified) {
    console.log(
      `pi adapter: project-stack overlay skipped (${STACK_OVERLAY_REL} is the unmodified template — customise it to append it to ${APPEND_SYSTEM_REL})`,
    );
    return null;
  }
  return stripFrontMatterAndMarker(overlay);
}

function buildAppendSystem(map, repoRoot, targetRoot, frameworkPrefix, promptIds) {
  const rulesRel = ssotPath(frameworkPrefix, ".ai/rules");
  const parts = [
    "# Agent Collections — always-on project rules (Pi)",
    "",
    GENERATED_MARKER,
    "",
    `> Generated from the Agent Collections SSOT (\`${rulesRel}\`) by \`adapters/pi/generate.mjs\`.`,
    "> Edit the sources, not this file, then re-run the adapter sync (installer or `node adapters/sync.mjs --agents pi`).",
    "",
    "## Pi surfaces",
    "",
    `- **Slash commands:** \`.pi/prompts/\` — ${promptIds.length} prompts, e.g. \`/eversis-implement\`, \`/eversis-review\`.`,
    "- **Framework skills:** `.pi/skills/eversis-*/` (mirror of `.ai/skills/`), also via the `eversis-collections` MCP (`eversis_skills_get`).",
    "- **Role-rule skills:** `.pi/skills/eversis-rule-*/` — load with `/skill:<name>` or read its `SKILL.md`.",
    "",
    "Rule ids used in prompts and skills map to Pi as follows:",
    "",
    "| Rule id | In Pi |",
    "| ------- | ----- |",
  ];
  for (const rule of map.rules) {
    let where;
    if (rule.target === "append_system") {
      where = "always on (this file)";
    } else if (rule.target === "skill") {
      where = `role skill \`/skill:${rule.skill_id}\``;
    } else if (rule.skill_id) {
      where = `framework skill \`/skill:${rule.skill_id}\``;
    } else {
      where = "not emitted for Pi";
    }
    parts.push(`| \`${rule.id}\` | ${where} |`);
  }

  for (const rule of map.rules.filter((r) => r.target === "append_system")) {
    const body = stripFrontMatterAndMarker(
      readFileOrFail(path.join(repoRoot, rule.source), `rule source for ${rule.id}`),
    );
    parts.push("", "---", "");
    if (rule.ui_note) {
      parts.push(
        "> Applies when editing UI files (`*.tsx`, `*.jsx`, `*.vue`, `*.html`, `*.svelte`).",
        "",
      );
    }
    parts.push(body);
  }

  const overlay = resolveStackOverlay(repoRoot, targetRoot);
  if (overlay) {
    parts.push(
      "",
      "---",
      "",
      `> Consumer overlay: \`${STACK_OVERLAY_REL}\` (project stack and skills policy).`,
      "",
      overlay,
    );
  }
  return parts.join("\n") + "\n";
}

/**
 * Writer / checker for one generation run. In check mode nothing is written;
 * each difference is recorded as a drift line naming the file.
 */
function createEmitter(targetRoot, check) {
  const drifts = [];
  const written = [];
  return {
    drifts,
    written,
    emit(relPath, content) {
      const abs = path.join(targetRoot, relPath);
      let prev = null;
      try {
        if (fs.statSync(abs).isFile()) prev = fs.readFileSync(abs, "utf8");
      } catch (err) {
        if (err.code !== "ENOENT" && err.code !== "ENOTDIR") throw err;
      }
      if (check) {
        if (prev === null) {
          drifts.push(`missing: ${abs}`);
        } else if (normalizeNewlines(prev) !== normalizeNewlines(content)) {
          drifts.push(`drift: ${abs}`);
        }
        return;
      }
      written.push(abs);
      if (prev === content) return;
      backupHandMadeTarget(targetRoot, abs);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      try {
        fs.lstatSync(abs);
        fs.unlinkSync(abs);
      } catch (err) {
        if (err.code !== "ENOENT") throw err;
      }
      fs.writeFileSync(abs, content, "utf8");
    },
    orphan(abs, removeAbs) {
      if (check) {
        drifts.push(`orphan: ${abs}`);
        return;
      }
      fs.rmSync(removeAbs, { recursive: true, force: true });
      written.push(`removed ${abs}`);
    },
  };
}

/** Compact local timestamp for backup names: YYYYMMDDTHHMMSS. */
function backupStamp(date = new Date()) {
  const pad = (n) => String(n).padStart(2, "0");
  return (
    `${date.getFullYear()}${pad(date.getMonth() + 1)}${pad(date.getDate())}` +
    `T${pad(date.getHours())}${pad(date.getMinutes())}${pad(date.getSeconds())}`
  );
}

/**
 * A target path that already holds a regular file without the GENERATED marker
 * was not written by this generator — it is the consumer's own file. Copy it
 * aside (byte-identical) before emit() unlinks and rewrites it, so a hand-made
 * .pi/APPEND_SYSTEM.md, prompt, role skill or extension is never lost. An
 * existing <name>.pre-agent-collections.bak is reused only when byte-identical;
 * otherwise a timestamped name is used so an older backup is never overwritten.
 * Symlinks and marker-bearing files are generator-owned: no backup. Mirrors
 * backupForeignClaudeMd in adapters/claude/generate.mjs. Write mode only.
 */
function backupHandMadeTarget(targetRoot, abs) {
  let stat;
  try {
    stat = fs.lstatSync(abs);
  } catch (err) {
    if (err.code === "ENOENT" || err.code === "ENOTDIR") return null;
    throw err;
  }
  if (!stat.isFile()) return null;

  const current = fs.readFileSync(abs);
  if (current.toString("utf8").includes(GENERATED_MARKER_PROBE)) return null;

  const dir = path.dirname(abs);
  const base = path.basename(abs);
  let backupAbs = path.join(dir, `${base}.pre-agent-collections.bak`);
  if (fs.existsSync(backupAbs) && !fs.readFileSync(backupAbs).equals(current)) {
    const stamp = backupStamp();
    backupAbs = path.join(dir, `${base}.pre-agent-collections.${stamp}.bak`);
    for (let n = 2; fs.existsSync(backupAbs) && !fs.readFileSync(backupAbs).equals(current); n++) {
      backupAbs = path.join(dir, `${base}.pre-agent-collections.${stamp}-${n}.bak`);
    }
  }
  if (!fs.existsSync(backupAbs)) fs.writeFileSync(backupAbs, current);
  const rel = (p) => path.relative(targetRoot, p).split(path.sep).join("/");
  console.warn(`warning: backed up hand-made ${rel(abs)} to ${rel(backupAbs)}`);
  return backupAbs;
}

function hasMarker(abs) {
  try {
    return fs.readFileSync(abs, "utf8").includes(GENERATED_MARKER_PROBE);
  } catch {
    return false;
  }
}

function cleanupOrphans(targetRoot, emitter, keepPromptIds, keepSkillIds) {
  const promptsDir = path.join(targetRoot, PROMPTS_DIR_REL);
  if (fs.existsSync(promptsDir)) {
    for (const name of fs.readdirSync(promptsDir).sort()) {
      if (!/^eversis-.*\.md$/.test(name)) continue;
      if (keepPromptIds.has(name.replace(/\.md$/, ""))) continue;
      const abs = path.join(promptsDir, name);
      if (!hasMarker(abs)) continue;
      emitter.orphan(abs, abs);
    }
  }
  const skillsDir = path.join(targetRoot, SKILLS_DIR_REL);
  if (fs.existsSync(skillsDir)) {
    for (const name of fs.readdirSync(skillsDir).sort()) {
      if (!name.startsWith(ROLE_SKILL_PREFIX)) continue;
      if (keepSkillIds.has(name)) continue;
      const skillMd = path.join(skillsDir, name, "SKILL.md");
      if (!hasMarker(skillMd)) continue;
      emitter.orphan(skillMd, path.join(skillsDir, name));
    }
  }
}

function seedSettings(targetRoot, check) {
  const abs = path.join(targetRoot, SETTINGS_REL);
  try {
    fs.lstatSync(abs);
    return false;
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  if (check) return false;
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.copyFileSync(SETTINGS_ASSET, abs);
  return true;
}

function generate(repoRoot, outRoot, frameworkPrefix, check) {
  const targetRoot = outRoot || repoRoot;
  const map = loadRuleMap(repoRoot);
  const deny = loadCommandDeny();
  const prompts = discoverPrompts(repoRoot, deny);
  const emitter = createEmitter(targetRoot, check);

  const piDir = path.join(targetRoot, PI_DIR_REL);
  if (fs.existsSync(piDir) && !fs.statSync(piDir).isDirectory()) {
    fail(`${piDir} exists and is not a directory`);
  }

  // 1. Always-on rules.
  emitter.emit(
    APPEND_SYSTEM_REL,
    buildAppendSystem(map, repoRoot, targetRoot, frameworkPrefix, prompts.map((p) => p.id)),
  );

  // 2. Role rules -> skills.
  const skillIds = new Set();
  for (const rule of map.rules.filter((r) => r.target === "skill")) {
    skillIds.add(rule.skill_id);
    emitter.emit(
      path.posix.join(SKILLS_DIR_REL, rule.skill_id, "SKILL.md"),
      buildRoleSkillContent(rule, repoRoot, frameworkPrefix),
    );
  }

  // 3. Prompts -> slash commands with $ARGUMENTS.
  const promptIds = new Set();
  for (const prompt of prompts) {
    const raw = readFileOrFail(path.join(repoRoot, prompt.sourceRel), `prompt ${prompt.id}`);
    promptIds.add(prompt.id);
    emitter.emit(
      path.posix.join(PROMPTS_DIR_REL, `${prompt.id}.md`),
      buildPromptContent(prompt, raw, frameworkPrefix),
    );
  }

  // 4. Context-budget extension (regenerated, marker-gated).
  const extensionSource = normalizeNewlines(readFileOrFail(EXTENSION_ASSET, "extension asset"));
  emitter.emit(EXTENSION_REL, `${GENERATED_MARKER_TS}\n${extensionSource}`);

  // 5. Orphans, then the consumer-owned settings seed.
  cleanupOrphans(targetRoot, emitter, promptIds, skillIds);
  if (!fs.existsSync(SETTINGS_ASSET)) fail(`missing settings asset: ${SETTINGS_ASSET}`);
  const seeded = seedSettings(targetRoot, check);

  return { emitter, promptCount: promptIds.size, skillCount: skillIds.size, seeded };
}

function main() {
  const { outRoot, frameworkPrefix, check } = parseArgs(process.argv.slice(2));
  const repoRoot = findRepoRoot(process.cwd());

  let result;
  try {
    result = generate(repoRoot, outRoot, frameworkPrefix, check);
  } catch (err) {
    fail(`Pi adapter generation failed: ${err && err.message ? err.message : err}`);
  }
  const { emitter, promptCount, skillCount, seeded } = result;

  if (check) {
    if (emitter.drifts.length > 0) {
      console.error("error: Pi adapter drift detected:");
      for (const d of emitter.drifts) console.error(`  ${d}`);
      console.error(
        "hint: run `node adapters/pi/generate.mjs` (or `node adapters/sync.mjs --agents pi`) with the same --out / --framework-prefix, then re-check.",
      );
      process.exit(1);
    }
    console.log("pi adapter check: OK (no drift)");
    return;
  }

  const removed = emitter.written.filter((w) => w.startsWith("removed "));
  console.log(
    `generated Pi adapter: ${promptCount} prompt(s), ${skillCount} role skill(s), APPEND_SYSTEM.md, context-budget extension${seeded ? ", settings.json (seeded)" : ""}`,
  );
  if (removed.length > 0) {
    console.log(`removed ${removed.length} orphan generated file(s):`);
    for (const r of removed) console.log(`  ${r.slice("removed ".length)}`);
  }
}

main();
