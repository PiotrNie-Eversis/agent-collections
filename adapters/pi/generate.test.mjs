test("prompt bodies: no Pi substitution pattern outside the final input line and the SSOT line", () => {
  let neutralised = 0;
  for (const name of fs.readdirSync(path.join(fresh, ".pi", "prompts"))) {
    const text = fs.readFileSync(path.join(fresh, ".pi", "prompts", name), "utf8");
    const lines = readFrontMatter(text).body.split("\n");
    const lastIdx = lines.map((l) => l.trim()).lastIndexOf(USER_INPUT_LINE);
    assert.notEqual(lastIdx, -1, name);
    lines.forEach((line, i) => {
      if (i === lastIdx || line.startsWith("> SSOT: ")) return;
      assert.doesNotMatch(line, PI_SUBSTITUTION_RE, `${name}:${i}: ${line}`);
    });
    if (text.includes("＄")) neutralised++;
  }
  assert.ok(neutralised >= 1, "SSOT dollar amounts were neutralised to U+FF04");
});

