test("stack overlay: absent / unmodified template / placeholder seed skipped; customised appended", () => {
  const template = fs.readFileSync(
    path.join(REPO_ROOT, "templates", "eversis-project-stack.example.mdc"),
    "utf8",
  );
  const overlayPath = (out) => path.join(out, ".cursor", "rules", "eversis-project-stack.mdc");
  const appendSystem = (out) => fs.readFileSync(path.join(out, ".pi", "APPEND_SYSTEM.md"), "utf8");

  const absent = mkTmp();
  const r0 = generate(absent);
  assert.match(r0.stdout, /project-stack overlay skipped/);
  assert.ok(!appendSystem(absent).includes("Consumer overlay:"));

  const unmodified = mkTmp();
  fs.mkdirSync(path.dirname(overlayPath(unmodified)), { recursive: true });
  fs.writeFileSync(overlayPath(unmodified), template.replace(/\n/g, "\r\n"));
  const r1 = generate(unmodified);
  assert.match(r1.stdout, /unmodified template/);
  assert.ok(!appendSystem(unmodified).includes("Consumer overlay:"));

  const olderSeed = mkTmp();
  fs.mkdirSync(path.dirname(overlayPath(olderSeed)), { recursive: true });
  fs.writeFileSync(overlayPath(olderSeed), `${template}\nextra line from an older template\n`);
  generate(olderSeed);
  assert.ok(!appendSystem(olderSeed).includes("Consumer overlay:"), "placeholder markers still present");

  const customised = mkTmp();
  fs.mkdirSync(path.dirname(overlayPath(customised)), { recursive: true });
  fs.writeFileSync(
    overlayPath(customised),
    '---\ndescription: "Project stack — Acme shop"\nalwaysApply: true\n---\n\n# Project stack — Acme\n\nUse pnpm. Backend in apps/api.\n',
  );
  generate(customised);
  const text = appendSystem(customised);
  assert.ok(text.includes("Consumer overlay: `.cursor/rules/eversis-project-stack.mdc`"));
  assert.ok(text.includes("# Project stack — Acme\n\nUse pnpm. Backend in apps/api."));
  assert.ok(!text.includes("alwaysApply: true"), "overlay front matter stripped");
  assert.equal(check(customised).status, 0);
});

