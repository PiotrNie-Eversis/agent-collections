/**
 * Tests for adapters/pi/generate.mjs (AC-14).
 * Runs the generator CLI into temp directories; counts are computed from
 * .ai/ and the rule map, never hard-coded. Zero dependencies (front matter is
 * checked with a minimal key + JSON-string parser).
 *
 * Run: node --test 'adapters/pi/*.test.mjs'
 */

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, test } from "node:test";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, "..", "..");
const GENERATOR = path.join(__dirname, "generate.mjs");
const MARKER = "GENERATED by adapters/pi/generate.mjs";
const USER_INPUT_LINE = "**User input for this run:** $ARGUMENTS";
const PLACEHOLDER = "/* eversis:process-skill-ids */";
/** Pi 1.4.0 dist/core/prompt-templates.js substituteArgs pattern (verbatim). */
const PI_SUBSTITUTION_RE =
  /\$\{(\d+|ARGUMENTS|@):-([^}]*)\}|\$\{@:(\d+)(?::(\d+))?\}|\$(ARGUMENTS|@|\d+)/;

const tmpDirs = [];
function mkTmp() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pi-adapter-test-"));
  tmpDirs.push(dir);
  return dir;
}
after(() => {
  for (const dir of tmpDirs) fs.rmSync(dir, { recursive: true, force: true });
});

function run(args) {
  const result = spawnSync(process.execPath, [GENERATOR, ...args], {
    cwd: REPO_ROOT,
    encoding: "utf8",
  });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

function generate(out, extra = []) {
  const r = run(["--out", out, ...extra]);
  assert.equal(r.status, 0, `generate failed: ${r.stderr}`);
  return r;
}

function check(out, extra = []) {
  return run(["--out", out, "--check", ...extra]);
}

/** Minimal front-matter reader: every value must be a JSON-quoted string. */
function readFrontMatter(text) {
  assert.ok(text.startsWith("---\n"), "front matter opens on line 1");
  const end = text.indexOf("\n---", 3);
  assert.notEqual(end, -1, "front matter closes");
  const fm = {};
  for (const line of text.slice(4, end).split("\n")) {
    const idx = line.indexOf(": ");
    assert.notEqual(idx, -1, `front-matter line has key: ${line}`);
    const value = line.slice(idx + 2);
    assert.ok(value.startsWith('"') && value.endsWith('"'), `value is JSON-quoted: ${line}`);
    fm[line.slice(0, idx)] = JSON.parse(value);
  }
  return { fm, body: text.slice(end + 4) };
}

function expectedPromptIds() {
  const denyText = fs.readFileSync(
    path.join(REPO_ROOT, "adapters", "claude", "command-deny.yaml"),
    "utf8",
  );
  const deny = new Set(
    [...denyText.matchAll(/^\s+-\s+(\S+)/gm)].map((m) => m[1].replace(/^["']|["']$/g, "")),
  );
  const ids = [];
  for (const bucket of ["public", "internal"]) {
    const dir = path.join(REPO_ROOT, ".ai", "prompts", bucket);
    for (const name of fs.readdirSync(dir)) {
      if (!/^eversis-.*\.md$/.test(name)) continue;
      const id = name.replace(/\.md$/, "");
      if (!deny.has(id)) ids.push(id);
    }
  }
  return ids.sort();
}

function ruleMapEntries() {
  const text = fs.readFileSync(path.join(__dirname, "rule-map.yaml"), "utf8");
  const rules = [];
  let current = null;
  for (const line of text.split("\n")) {
    const item = line.match(/^ {2}- (\w+):\s*(.*)$/);
    if (item) {
      current = { [item[1]]: item[2] };
      rules.push(current);
      continue;
    }
    const field = line.match(/^ {4}(\w+):\s*(.*)$/);
    if (field && current) current[field[1]] = field[2];
  }
  return rules;
}

function frameworkSkillNames() {
  return fs
    .readdirSync(path.join(REPO_ROOT, ".ai", "skills"), { withFileTypes: true })
    .filter((e) => e.isDirectory() && e.name.startsWith("eversis-"))
    .map((e) => e.name);
}

/**
 * Runs a copy of the generator (assets included) beside a transformed rule map
 * and, when given, a transformed process-rules asset.
 */
function runFixture(transformMap = (map) => map, transformAsset = null) {
  const dir = path.join(mkTmp(), "adapter");
  fs.mkdirSync(dir);
  fs.copyFileSync(GENERATOR, path.join(dir, "generate.mjs"));
  fs.cpSync(path.join(__dirname, "assets"), path.join(dir, "assets"), { recursive: true });
  const mapText = fs.readFileSync(path.join(__dirname, "rule-map.yaml"), "utf8");
  fs.writeFileSync(path.join(dir, "rule-map.yaml"), transformMap(mapText));
  if (transformAsset) {
    const assetPath = path.join(dir, "assets", "eversis-process-rules.ts");
    fs.writeFileSync(assetPath, transformAsset(fs.readFileSync(assetPath, "utf8")));
  }
  return spawnSync(process.execPath, [path.join(dir, "generate.mjs"), "--out", mkTmp()], {
    cwd: REPO_ROOT,
    encoding: "utf8",
  });
}

