#!/usr/bin/env node
/**
 * Cursor adapter generator (TASK-524 rules + TASK-598 slash commands).
 * - Reads adapters/cursor/rule-map.yaml → .cursor/rules/*.mdc from .ai/rules
 * - Discovers .ai/prompts/{public,internal}/eversis-*.md → thin HYBRID
 *   shims under .cursor/commands/ (pointer + optional Executable section)
 * Zero npm dependencies.
 *
 * Usage (repo root):
 *   node adapters/cursor/generate.mjs
 *   node adapters/cursor/generate.mjs --out /path/to/out
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_MARKER =
  "<!-- GENERATED by adapters/cursor/generate.mjs — do not edit; re-run the generator -->";

const PROMPT_BUCKETS = ["public", "internal"];
const COMMANDS_DIR_REL = ".cursor/commands";
const EXECUTABLE_HEADING_RE = /^## Executable prompt\b.*$/m;

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ADAPTER_DIR = __dirname;
const MAP_PATH = path.join(ADAPTER_DIR, "rule-map.yaml");
const DENY_PATH = path.join(ADAPTER_DIR, "command-deny.yaml");

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function findRepoRoot(startDir) {
  let dir = startDir;
  for (;;) {
    if (
      fs.existsSync(path.join(dir, ".ai")) &&
      fs.existsSync(path.join(dir, "adapters"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      fail(
        "could not find repository root (expected .ai/ and adapters/). Run from repo root.",
      );
    }
    dir = parent;
  }
}

function parseArgs(argv) {
  let outRoot = null;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--out requires a directory path");
      }
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: node adapters/cursor/generate.mjs [--out <dir>]\n" +
          "  Default: write rule-map outputs and .cursor/commands/ (repo-relative).\n" +
          "  --out: write under <dir>, preserving .cursor/rules/… and .cursor/commands/… tails.",
      );
      process.exit(0);
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot };
}

function stripQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function parseScalar(raw) {
  const value = raw.trim();
  if (value === "true") return true;
  if (value === "false") return false;
  if (value === "[]") return [];
  if (/^-?\d+$/.test(value)) return Number(value);
  return stripQuotes(value);
}

/**
 * Constrained YAML parser for rule-map.yaml shape only.
 * Supports: version, rules[] with scalar keys and globs string arrays.
 */
function parseRuleMapYaml(text) {
  const lines = text.split(/\r?\n/);
  const doc = { version: null, rules: [] };
  let currentRule = null;
  let inGlobs = false;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.replace(/\s+#.*$/, "");
    if (!line.trim() || line.trim().startsWith("#")) continue;

    const indent = line.match(/^ */)[0].length;
    const trimmed = line.trim();

    if (indent === 0 && trimmed.startsWith("version:")) {
      doc.version = parseScalar(trimmed.slice("version:".length));
      inGlobs = false;
      continue;
    }

    if (indent === 0 && trimmed === "rules:") {
      inGlobs = false;
      continue;
    }

    if (indent === 2 && trimmed.startsWith("- ")) {
      currentRule = {};
      doc.rules.push(currentRule);
      inGlobs = false;
      const rest = trimmed.slice(2).trim();
      if (rest.includes(":")) {
        const idx = rest.indexOf(":");
        const key = rest.slice(0, idx).trim();
        const val = rest.slice(idx + 1).trim();
        if (val === "") {
          // e.g. "- globs:" unlikely at this indent
        } else {
          currentRule[key] = parseScalar(val);
        }
      }
      continue;
    }

    if (!currentRule) {
      fail(`unexpected line ${i + 1}: ${rawLine}`);
    }

    if (indent === 4 && trimmed.startsWith("globs:")) {
      const inline = trimmed.slice("globs:".length).trim();
      if (inline === "[]" || inline === "") {
        currentRule.globs = inline === "[]" ? [] : [];
        inGlobs = inline === "";
      } else {
        currentRule.globs = [parseScalar(inline)];
        inGlobs = false;
      }
      continue;
    }

    if (inGlobs && indent >= 6 && trimmed.startsWith("- ")) {
      currentRule.globs.push(parseScalar(trimmed.slice(2).trim()));
      continue;
    }

    if (indent === 4 && trimmed.includes(":")) {
      inGlobs = false;
      const idx = trimmed.indexOf(":");
      const key = trimmed.slice(0, idx).trim();
      const val = trimmed.slice(idx + 1).trim();
      if (val === "" && key === "globs") {
        currentRule.globs = [];
        inGlobs = true;
      } else {
        currentRule[key] = parseScalar(val);
      }
      continue;
    }

    fail(`unexpected line ${i + 1}: ${rawLine}`);
  }

  return doc;
}

function assertSafeRepoRelative(relPath, label) {
  if (!relPath || typeof relPath !== "string") {
    fail(`${label} must be a non-empty string`);
  }
  if (path.isAbsolute(relPath)) {
    fail(`${label} must be repo-relative (got absolute path): ${relPath}`);
  }
  const normalized = path.normalize(relPath);
  if (normalized.startsWith("..") || path.isAbsolute(normalized)) {
    fail(`${label} escapes repository root: ${relPath}`);
  }
  return normalized.split(path.sep).join("/");
}

function validateRule(rule, index) {
  const prefix = `rules[${index}]`;
  for (const key of ["id", "source", "output", "description"]) {
    if (rule[key] === undefined || rule[key] === null || rule[key] === "") {
      fail(`${prefix}: missing required field "${key}"`);
    }
  }
  rule.source = assertSafeRepoRelative(String(rule.source), `${prefix}.source`);
  rule.output = assertSafeRepoRelative(String(rule.output), `${prefix}.output`);

  const hasAlways = Object.prototype.hasOwnProperty.call(rule, "alwaysApply");
  const hasGlobs = Object.prototype.hasOwnProperty.call(rule, "globs");
  if (!hasAlways && !hasGlobs) {
    fail(`${prefix} (${rule.id}): need alwaysApply and/or globs`);
  }
  if (hasGlobs && !Array.isArray(rule.globs)) {
    fail(`${prefix} (${rule.id}): globs must be an array`);
  }
}

function buildFrontMatter(rule) {
  const lines = ["---", `description: ${JSON.stringify(String(rule.description))}`];
  if (Object.prototype.hasOwnProperty.call(rule, "globs")) {
    if (rule.globs.length === 0) {
      lines.push("globs: []");
    } else {
      lines.push("globs:");
      for (const g of rule.globs) {
        lines.push(`  - ${JSON.stringify(String(g))}`);
      }
    }
  }
  if (Object.prototype.hasOwnProperty.call(rule, "alwaysApply")) {
    lines.push(`alwaysApply: ${rule.alwaysApply ? "true" : "false"}`);
  }
  lines.push("---");
  return lines.join("\n");
}

function resolveOutputPath(repoRoot, outRoot, outputRel) {
  if (!outRoot) {
    return path.join(repoRoot, outputRel);
  }
  return path.join(outRoot, outputRel);
}

function writeRule(repoRoot, outRoot, rule) {
  const sourceAbs = path.join(repoRoot, rule.source);
  if (!fs.existsSync(sourceAbs)) {
    fail(`source not found for ${rule.id}: ${rule.source}`);
  }
  const body = fs.readFileSync(sourceAbs, "utf8").replace(/^\uFEFF/, "");
  const content = `${buildFrontMatter(rule)}\n${GENERATED_MARKER}\n\n${body.replace(/\s+$/, "")}\n`;

  const destAbs = resolveOutputPath(repoRoot, outRoot, rule.output);
  fs.mkdirSync(path.dirname(destAbs), { recursive: true });

  // Replace existing file or symlink for mapped outputs only
  try {
    fs.lstatSync(destAbs);
    fs.unlinkSync(destAbs);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }

  fs.writeFileSync(destAbs, content, "utf8");
  return destAbs;
}

/**
 * Minimal deny-list parser: version + deny: [] or deny: with "- id" items.
 */
function parseCommandDenyYaml(text) {
  const lines = text.split(/\r?\n/);
  const doc = { version: null, deny: [] };
  let inDeny = false;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.replace(/\s+#.*$/, "");
    if (!line.trim() || line.trim().startsWith("#")) continue;

    const indent = line.match(/^ */)[0].length;
    const trimmed = line.trim();

    if (indent === 0 && trimmed.startsWith("version:")) {
      doc.version = parseScalar(trimmed.slice("version:".length));
      inDeny = false;
      continue;
    }

    if (indent === 0 && trimmed.startsWith("deny:")) {
      const inline = trimmed.slice("deny:".length).trim();
      if (inline === "[]") {
        doc.deny = [];
        inDeny = false;
      } else if (inline === "") {
        doc.deny = [];
        inDeny = true;
      } else {
        fail(`command-deny.yaml: unsupported inline deny value at line ${i + 1}`);
      }
      continue;
    }

    if (inDeny && indent >= 2 && trimmed.startsWith("- ")) {
      doc.deny.push(String(parseScalar(trimmed.slice(2).trim())));
      continue;
    }

    fail(`command-deny.yaml: unexpected line ${i + 1}: ${rawLine}`);
  }

  return doc;
}

function loadCommandDeny() {
  if (!fs.existsSync(DENY_PATH)) {
    return new Set();
  }
  const doc = parseCommandDenyYaml(fs.readFileSync(DENY_PATH, "utf8"));
  if (doc.version !== 1) {
    fail(`unsupported command-deny version: ${doc.version} (expected 1)`);
  }
  if (!Array.isArray(doc.deny)) {
    fail("command-deny.yaml: deny must be an array");
  }
  return new Set(doc.deny.map(String));
}

function discoverPromptCommands(repoRoot, deny) {
  /** @type {{ id: string, sourceRel: string, audience: string }[]} */
  const found = [];
  const seen = new Set();

  for (const audience of PROMPT_BUCKETS) {
    const dirRel = path.posix.join(".ai/prompts", audience);
    const dirAbs = path.join(repoRoot, ".ai", "prompts", audience);
    if (!fs.existsSync(dirAbs)) continue;

    for (const name of fs.readdirSync(dirAbs).sort()) {
      if (!/^eversis-.*\.md$/.test(name)) continue;
      const id = name.replace(/\.md$/, "");
      if (deny.has(id)) continue;
      if (seen.has(id)) {
        fail(`duplicate prompt id across buckets: ${id}`);
      }
      seen.add(id);
      found.push({
        id,
        sourceRel: path.posix.join(dirRel, name),
        audience,
      });
    }
  }

  found.sort((a, b) => a.id.localeCompare(b.id));
  return found;
}

/**
 * HYBRID: extract "## Executable prompt…" through next same-level ## or EOF.
 * @returns {string|null}
 */
function extractExecutableSection(body) {
  const match = EXECUTABLE_HEADING_RE.exec(body);
  if (!match || match.index === undefined) return null;

  const start = match.index;
  const afterHeading = start + match[0].length;
  const rest = body.slice(afterHeading);
  const nextHeading = rest.search(/\n## /);
  const section =
    nextHeading === -1
      ? body.slice(start)
      : body.slice(start, afterHeading + nextHeading);
  return section.replace(/\s+$/, "");
}

/**
 * Read prompt YAML frontmatter keys used for slash-menu summary text.
 * @returns {{ prompt_description?: string, title?: string }}
 */
function extractPromptMeta(body) {
  const meta = {};
  if (!body.startsWith("---")) return meta;
  const end = body.indexOf("\n---", 3);
  if (end === -1) return meta;
  const fm = body.slice(3, end);
  for (const rawLine of fm.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    if (key !== "prompt_description" && key !== "title") continue;
    meta[key] = String(parseScalar(line.slice(idx + 1)));
  }
  return meta;
}

/**
 * Cursor slash UI often shows the first plain paragraph after the title as the
 * command summary — do not put GENERATED HTML comments there.
 */
function buildCommandContent(prompt, sourceBody) {
  const meta = extractPromptMeta(sourceBody);
  const summary =
    (meta.prompt_description && String(meta.prompt_description).trim()) ||
    (meta.title && String(meta.title).trim()) ||
    `Run Agent Collections prompt ${prompt.id}`;

  const lines = [
    `# ${prompt.id}`,
    "",
    summary,
    "",
    `**Stable id:** \`${prompt.id}\`  `,
    `**Audience:** ${prompt.audience}  `,
    `**SSOT:** \`${prompt.sourceRel}\``,
    "",
    "Load and follow the Agent Collections prompt at the SSOT path above.",
    "Prefer that file over any docs-site copy under `website/docs/prompts/`.",
    "",
  ];

  const executable = extractExecutableSection(sourceBody);
  if (executable) {
    lines.push(executable, "");
  } else {
    lines.push(
      "_No `## Executable prompt` section found in SSOT — open the SSOT file and follow its workflow._",
      "",
    );
  }

  lines.push(GENERATED_MARKER, "");
  return lines.join("\n");
}

function writeCommand(repoRoot, outRoot, prompt) {
  const sourceAbs = path.join(repoRoot, prompt.sourceRel);
  if (!fs.existsSync(sourceAbs)) {
    fail(`prompt source not found for ${prompt.id}: ${prompt.sourceRel}`);
  }
  const body = fs.readFileSync(sourceAbs, "utf8").replace(/^\uFEFF/, "");
  const content = buildCommandContent(prompt, body);
  const outputRel = path.posix.join(COMMANDS_DIR_REL, `${prompt.id}.md`);
  const destAbs = resolveOutputPath(repoRoot, outRoot, outputRel);

  fs.mkdirSync(path.dirname(destAbs), { recursive: true });
  try {
    fs.lstatSync(destAbs);
    fs.unlinkSync(destAbs);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }

  fs.writeFileSync(destAbs, content, "utf8");
  return { destAbs, outputRel };
}

function cleanupOrphanCommands(repoRoot, outRoot, keepIds) {
  const commandsDir = resolveOutputPath(repoRoot, outRoot, COMMANDS_DIR_REL);
  if (!fs.existsSync(commandsDir)) return [];

  const removed = [];
  for (const name of fs.readdirSync(commandsDir)) {
    if (!/^eversis-.*\.md$/.test(name)) continue;
    const id = name.replace(/\.md$/, "");
    const abs = path.join(commandsDir, name);
    let text = "";
    try {
      text = fs.readFileSync(abs, "utf8");
    } catch {
      continue;
    }
    if (!text.includes(GENERATED_MARKER)) continue;
    if (keepIds.has(id)) continue;
    fs.unlinkSync(abs);
    removed.push(abs);
  }
  return removed;
}

function generateCommands(repoRoot, outRoot) {
  const deny = loadCommandDeny();
  const prompts = discoverPromptCommands(repoRoot, deny);
  const written = [];
  const keepIds = new Set();

  for (const prompt of prompts) {
    keepIds.add(prompt.id);
    written.push(writeCommand(repoRoot, outRoot, prompt));
  }

  const removed = cleanupOrphanCommands(repoRoot, outRoot, keepIds);
  return { written, removed, denied: [...deny].sort() };
}

function main() {
  const { outRoot } = parseArgs(process.argv.slice(2));
  const repoRoot = findRepoRoot(process.cwd());

  if (!fs.existsSync(MAP_PATH)) {
    fail(`rule map not found: ${MAP_PATH}`);
  }

  const map = parseRuleMapYaml(fs.readFileSync(MAP_PATH, "utf8"));
  if (map.version !== 1) {
    fail(`unsupported rule-map version: ${map.version} (expected 1)`);
  }
  if (!Array.isArray(map.rules) || map.rules.length === 0) {
    fail("rule-map has no rules");
  }

  map.rules.forEach(validateRule);

  const writtenRules = [];
  for (const rule of map.rules) {
    writtenRules.push(writeRule(repoRoot, outRoot, rule));
  }

  console.log(`generated ${writtenRules.length} Cursor rule(s):`);
  for (const p of writtenRules) {
    console.log(`  ${path.relative(process.cwd(), p) || p}`);
  }

  const { written: writtenCmds, removed, denied } = generateCommands(
    repoRoot,
    outRoot,
  );
  console.log(`generated ${writtenCmds.length} Cursor slash command(s):`);
  for (const { destAbs } of writtenCmds) {
    console.log(`  ${path.relative(process.cwd(), destAbs) || destAbs}`);
  }
  if (denied.length > 0) {
    console.log(`command deny-list skipped ${denied.length} id(s): ${denied.join(", ")}`);
  }
  if (removed.length > 0) {
    console.log(`removed ${removed.length} orphan generated command(s):`);
    for (const p of removed) {
      console.log(`  ${path.relative(process.cwd(), p) || p}`);
    }
  }
}

main();
