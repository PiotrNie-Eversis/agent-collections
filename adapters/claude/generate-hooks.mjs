#!/usr/bin/env node
/**
 * Claude Code hooks generator.
 *
 * Writes .claude/hooks/eversis-validate-spec.cjs, the spec artifact hook
 * launcher that checks research and plan files under docs/specs/ against the
 * framework templates (see adapters/claude/assets/eversis-validate-spec.cjs
 * for its behaviour). Claude Code runs the same launcher for two hook
 * events: PreToolUse on Bash, where it only records when a shell command
 * starts, and PostToolUse on Write|Edit|MultiEdit|Bash, where it validates
 * the spec artifact an edit tool wrote, or every spec artifact a shell
 * command changed since that start.
 *
 * The launcher source is copied as is, with two changes: the framework
 * prefix placeholder is replaced by --framework-prefix
 * (so the launcher finds scripts/validate-spec-artifacts.mjs in self-host,
 * vendored and local-mode installs), and the GENERATED marker comment is
 * appended. Marker-bearing .claude/hooks/eversis-*.cjs files that this
 * generator no longer writes are removed; hand-made files are kept.
 *
 * The two settings entries that run the launcher are owned by the installer's
 * settings merge (scripts/lib/setup-agent-collections/claude-settings-merge.mjs),
 * not by this generator. Zero npm dependencies.
 *
 * Usage (repo root):
 *   node adapters/claude/generate-hooks.mjs
 *   node adapters/claude/generate-hooks.mjs --out /path/to/out --framework-prefix vendor/agent-collections
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_MARKER =
  "// GENERATED by adapters/claude/generate-hooks.mjs — do not edit; re-run the generator";

const HOOKS_DIR_REL = ".claude/hooks";
const PREFIX_PLACEHOLDER = '"__EVERSIS_FRAMEWORK_PREFIX__"';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ADAPTER_DIR = __dirname;

/** Launcher sources under assets/, keyed by the generated file name. */
const HOOK_SOURCES = [
  {
    name: "eversis-validate-spec.cjs",
    source: path.join(ADAPTER_DIR, "assets", "eversis-validate-spec.cjs"),
  },
];

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function findRepoRoot(startDir) {
  let dir = startDir;
  for (;;) {
    if (
      fs.existsSync(path.join(dir, ".ai")) &&
      fs.existsSync(path.join(dir, "adapters"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      fail(
        "could not find repository root (expected .ai/ and adapters/). Run from repo root.",
      );
    }
    dir = parent;
  }
}

// Same permissive check as adapters/claude/generate-commands.mjs's
// assertSafeFrameworkPrefix — the prefix may be a literal env-var token
// (${AGENT_COLLECTIONS_HOME}) in local vendor mode, not always a real path.
function assertSafeFrameworkPrefix(value) {
  if (value.startsWith("/")) {
    fail(`--framework-prefix must not be an absolute path: ${value}`);
  }
  if (value.split("/").some((segment) => segment === "..")) {
    fail(`--framework-prefix must not escape the target root: ${value}`);
  }
  return value.replace(/\/+$/, "");
}

function parseArgs(argv) {
  let outRoot = null;
  let frameworkPrefix = "";
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--out requires a directory path");
      }
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    if (arg === "--framework-prefix") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--framework-prefix requires a value");
      }
      frameworkPrefix = assertSafeFrameworkPrefix(next);
      i++;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: node adapters/claude/generate-hooks.mjs [--out <dir>] [--framework-prefix <path>]\n" +
          "  Default: write .claude/hooks/ (repo-relative).\n" +
          "  --out: write under <dir>, preserving the .claude/hooks/… tail.\n" +
          "  --framework-prefix: where the framework lives relative to the target\n" +
          "    (vendor/agent-collections, or the ${AGENT_COLLECTIONS_HOME} token in\n" +
          "    local mode). The launcher resolves scripts/validate-spec-artifacts.mjs\n" +
          "    under it. Empty = self-host.",
      );
      process.exit(0);
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot, frameworkPrefix };
}

/**
 * Generated launcher text: placeholder replaced, marker appended.
 * @param {string} sourceText
 * @param {string} frameworkPrefix
 * @returns {string}
 */
export function buildHookContent(sourceText, frameworkPrefix) {
  const parts = sourceText.split(PREFIX_PLACEHOLDER);
  if (parts.length !== 2) {
    throw new Error(
      `launcher source must contain the prefix placeholder exactly once (found ${parts.length - 1})`,
    );
  }
  const body = parts.join(JSON.stringify(frameworkPrefix)).replace(/\s+$/, "");
  return `${body}\n\n${GENERATED_MARKER}\n`;
}

function writeHook(targetRoot, hook, frameworkPrefix) {
  if (!fs.existsSync(hook.source)) {
    fail(`launcher source not found: ${hook.source}`);
  }
  const sourceText = fs.readFileSync(hook.source, "utf8").replace(/^﻿/, "");
  let content;
  try {
    content = buildHookContent(sourceText, frameworkPrefix);
  } catch (err) {
    fail(`${hook.name}: ${err.message}`);
  }
  const destAbs = path.join(targetRoot, HOOKS_DIR_REL, hook.name);
  fs.mkdirSync(path.dirname(destAbs), { recursive: true });
  try {
    fs.lstatSync(destAbs);
    fs.unlinkSync(destAbs);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  fs.writeFileSync(destAbs, content, "utf8");
  return destAbs;
}

function cleanupOrphanHooks(targetRoot, keepNames) {
  const hooksDir = path.join(targetRoot, HOOKS_DIR_REL);
  if (!fs.existsSync(hooksDir)) return [];
  const removed = [];
  for (const name of fs.readdirSync(hooksDir)) {
    if (!/^eversis-.*\.cjs$/.test(name)) continue;
    if (keepNames.has(name)) continue;
    const abs = path.join(hooksDir, name);
    let text = "";
    try {
      text = fs.readFileSync(abs, "utf8");
    } catch {
      continue;
    }
    if (!text.includes(GENERATED_MARKER)) continue;
    fs.unlinkSync(abs);
    removed.push(abs);
  }
  return removed;
}

function main() {
  const { outRoot, frameworkPrefix } = parseArgs(process.argv.slice(2));
  const targetRoot = outRoot || findRepoRoot(process.cwd());
  const written = HOOK_SOURCES.map((hook) => writeHook(targetRoot, hook, frameworkPrefix));
  const removed = cleanupOrphanHooks(
    targetRoot,
    new Set(HOOK_SOURCES.map((hook) => hook.name)),
  );
  console.log(`generated ${written.length} Claude Code hook launcher(s):`);
  for (const p of written) {
    console.log(`  ${path.relative(process.cwd(), p) || p}`);
  }
  if (removed.length > 0) {
    console.log(`removed ${removed.length} orphan generated hook launcher(s):`);
    for (const p of removed) {
      console.log(`  ${path.relative(process.cwd(), p) || p}`);
    }
  }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  main();
}
