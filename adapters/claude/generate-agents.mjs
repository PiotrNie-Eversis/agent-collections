#!/usr/bin/env node
/**
 * Claude Code role subagent generator.
 *
 * Reads adapters/claude/agent-map.yaml and writes one thin-pointer subagent
 * per role under .claude/agents/<id>.md, so the Engineering Manager can
 * delegate research, planning and review to a subagent whose first act is
 * reading the role prompt, the skill and the template — instead of writing
 * the artifact from memory or from an earlier docs/specs/ file.
 *
 * Same contract as adapters/claude/generate-commands.mjs: the GENERATED
 * marker sits at the end of each file, marker-bearing .claude/agents/eversis-*.md
 * files that the map no longer lists are removed (hand-made files are kept),
 * and every read path is rewritten through --framework-prefix so it resolves
 * in vendored and local-mode installs, not just self-host.
 *
 * Frontmatter: `name`, `description`, optional `tools` (Claude Code
 * allow-list) and optional `readonly` (read by Cursor, which also loads
 * .claude/agents/). The body is generated, not copied: the role prompts stay
 * the single source of the workflow. Zero npm dependencies.
 *
 * Usage (repo root):
 *   node adapters/claude/generate-agents.mjs
 *   node adapters/claude/generate-agents.mjs --out /path/to/out --framework-prefix vendor/agent-collections
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_MARKER =
  "<!-- GENERATED by adapters/claude/generate-agents.mjs — do not edit; re-run the generator -->";

const AGENTS_DIR_REL = ".claude/agents";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ADAPTER_DIR = __dirname;
export const AGENT_MAP_PATH = path.join(ADAPTER_DIR, "agent-map.yaml");

/** Error raised by the map parser; main() turns it into a clean exit. */
class MapError extends Error {}

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function findRepoRoot(startDir) {
  let dir = startDir;
  for (;;) {
    if (
      fs.existsSync(path.join(dir, ".ai")) &&
      fs.existsSync(path.join(dir, "adapters"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      fail(
        "could not find repository root (expected .ai/ and adapters/). Run from repo root.",
      );
    }
    dir = parent;
  }
}

// Same permissive check as adapters/claude/generate-commands.mjs's
// assertSafeFrameworkPrefix — the prefix may be a literal env-var token
// (${AGENT_COLLECTIONS_HOME}) in local vendor mode, not always a real path.
function assertSafeFrameworkPrefix(value) {
  if (value.startsWith("/")) {
    fail(`--framework-prefix must not be an absolute path: ${value}`);
  }
  if (value.split("/").some((segment) => segment === "..")) {
    fail(`--framework-prefix must not escape the target root: ${value}`);
  }
  return value.replace(/\/+$/, "");
}

function parseArgs(argv) {
  let outRoot = null;
  let frameworkPrefix = "";
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--out requires a directory path");
      }
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    if (arg === "--framework-prefix") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--framework-prefix requires a value");
      }
      frameworkPrefix = assertSafeFrameworkPrefix(next);
      i++;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: node adapters/claude/generate-agents.mjs [--out <dir>] [--framework-prefix <path>]\n" +
          "  Default: write .claude/agents/ (repo-relative) from adapters/claude/agent-map.yaml.\n" +
          "  --out: write under <dir>, preserving the .claude/agents/… tail.\n" +
          "  --framework-prefix: prepend <path> to every read path in the generated\n" +
          "    bodies (see adapters/claude/generate.mjs). Empty = self-host.",
      );
      process.exit(0);
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot, frameworkPrefix };
}

function stripQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function parseScalar(raw) {
  const value = raw.trim();
  if (value === "true") return true;
  if (value === "false") return false;
  if (value === "[]") return [];
  if (/^-?\d+$/.test(value)) return Number(value);
  return stripQuotes(value);
}

const LIST_KEYS = new Set(["reads", "tools"]);
const SCALAR_KEYS = new Set(["id", "description", "readonly"]);

/**
 * Minimal parser for the role map: `version`, then `agents:` with
 * "- id: …" rows holding scalars (id, description, readonly) and
 * lists (reads, tools) of "- item" lines. Nothing else is accepted.
 * @param {string} text
 * @returns {{ version: number | null, agents: object[] }}
 */
export function parseAgentMapYaml(text) {
  const lines = text.split(/\r?\n/);
  const doc = { version: null, agents: [] };
  let inAgents = false;
  let current = null;
  let listKey = null;

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const line = rawLine.replace(/\s+#.*$/, "");
    if (!line.trim() || line.trim().startsWith("#")) continue;
    const indent = line.match(/^ */)[0].length;
    const trimmed = line.trim();
    const where = `agent-map.yaml line ${i + 1}`;

    if (indent === 0) {
      listKey = null;
      current = null;
      if (trimmed.startsWith("version:")) {
        doc.version = parseScalar(trimmed.slice("version:".length));
        inAgents = false;
        continue;
      }
      if (trimmed === "agents:") {
        inAgents = true;
        continue;
      }
      throw new MapError(`${where}: unexpected top-level key: ${rawLine}`);
    }
    if (!inAgents) throw new MapError(`${where}: unexpected line: ${rawLine}`);

    if (indent === 2 && trimmed.startsWith("- ")) {
      current = {};
      doc.agents.push(current);
      listKey = null;
      const rest = trimmed.slice(2).trim();
      const idx = rest.indexOf(":");
      if (idx === -1) throw new MapError(`${where}: expected "- id: <value>"`);
      assignKey(current, rest.slice(0, idx).trim(), rest.slice(idx + 1), where);
      continue;
    }
    if (!current) throw new MapError(`${where}: field outside an agent row: ${rawLine}`);

    if (indent === 4 && trimmed.includes(":") && !trimmed.startsWith("- ")) {
      const idx = trimmed.indexOf(":");
      const key = trimmed.slice(0, idx).trim();
      const val = trimmed.slice(idx + 1).trim();
      if (LIST_KEYS.has(key) && val === "") {
        current[key] = [];
        listKey = key;
        continue;
      }
      listKey = null;
      assignKey(current, key, val, where);
      continue;
    }
    if (listKey && indent >= 6 && trimmed.startsWith("- ")) {
      current[listKey].push(String(parseScalar(trimmed.slice(2))));
      continue;
    }
    throw new MapError(`${where}: unexpected line: ${rawLine}`);
  }
  return doc;
}

function assignKey(row, key, rawValue, where) {
  if (LIST_KEYS.has(key)) {
    const value = parseScalar(rawValue);
    if (!Array.isArray(value)) {
      throw new MapError(`${where}: ${key} must be a list of "- item" lines`);
    }
    row[key] = value;
    return;
  }
  if (!SCALAR_KEYS.has(key)) throw new MapError(`${where}: unknown key: ${key}`);
  row[key] = parseScalar(rawValue);
}

/**
 * Parse and check the map file.
 * @param {string} [mapPath]
 * @returns {{ id: string, description: string, reads: string[], tools?: string[], readonly?: boolean }[]}
 */
export function loadAgentMap(mapPath = AGENT_MAP_PATH) {
  if (!fs.existsSync(mapPath)) throw new MapError(`agent map not found: ${mapPath}`);
  const doc = parseAgentMapYaml(fs.readFileSync(mapPath, "utf8"));
  if (doc.version !== 1) {
    throw new MapError(`unsupported agent-map version: ${doc.version} (expected 1)`);
  }
  if (doc.agents.length === 0) throw new MapError("agent-map.yaml lists no agents");
  const seen = new Set();
  for (const row of doc.agents) {
    if (typeof row.id !== "string" || !/^eversis-[a-z0-9-]+$/.test(row.id)) {
      throw new MapError(`agent id must match eversis-<name>: ${JSON.stringify(row.id)}`);
    }
    if (seen.has(row.id)) throw new MapError(`duplicate agent id: ${row.id}`);
    seen.add(row.id);
    if (typeof row.description !== "string" || row.description.trim() === "") {
      throw new MapError(`${row.id}: description is required`);
    }
    if (!Array.isArray(row.reads) || row.reads.length === 0) {
      throw new MapError(`${row.id}: reads must list at least one file`);
    }
    if (row.readonly !== undefined && typeof row.readonly !== "boolean") {
      throw new MapError(`${row.id}: readonly must be true or false`);
    }
  }
  return doc.agents;
}

function prefixed(frameworkPrefix, relPath) {
  return frameworkPrefix ? `${frameworkPrefix}/${relPath}` : relPath;
}

function buildFrontMatter(agent) {
  const lines = [
    "---",
    `name: ${agent.id}`,
    `description: ${JSON.stringify(agent.description)}`,
  ];
  if (Array.isArray(agent.tools) && agent.tools.length > 0) {
    lines.push(`tools: ${agent.tools.join(", ")}`);
  }
  if (agent.readonly === true) lines.push("readonly: true");
  lines.push("---");
  return lines.join("\n");
}

/**
 * Generated subagent file text.
 * @param {{ id: string, description: string, reads: string[], tools?: string[], readonly?: boolean }} agent
 * @param {string} frameworkPrefix
 * @returns {string}
 */
export function buildAgentContent(agent, frameworkPrefix) {
  const lines = [
    buildFrontMatter(agent),
    "",
    `# ${agent.id}`,
    "",
    agent.description,
    "",
    "You are an Agent Collections role subagent. The Engineering Manager delegated one stage of the Implement workflow to you. Follow these steps in order:",
    "",
    "1. Read these files in full before you write anything:",
    ...agent.reads.map((rel) => `   - \`${prefixed(frameworkPrefix, rel)}\``),
    "2. Artifact structure (research or plan files) comes only from the template named above, never from earlier `docs/specs/*` files.",
    "3. When you create or update a research or plan file, its first Changelog row names the template used.",
    "4. When you are done, return the file path and a short summary. Do not ask the person for approval; the Engineering Manager owns the gate.",
    "5. Hand-back rule: you cannot talk to the person. When your prompt or skill says to ask the person for clarification, list the questions in your final message and stop; the Engineering Manager relays them. When it says to write something you have no access for, put the exact text in your final message; the Engineering Manager writes it.",
    "",
  ];
  if (agent.readonly === true) {
    lines.push(
      "## Review rules",
      "",
      "- Report findings as PASS / BLOCKER / SUGGESTION.",
      "- Never edit product files or any other file; you only read and run checks.",
      "- The review row for the plan Changelog is a write you have no access for: return its exact text in your final message (hand-back rule, step 5).",
      "",
    );
  }
  lines.push(GENERATED_MARKER, "");
  return lines.join("\n");
}

function writeAgent(targetRoot, agent, frameworkPrefix) {
  const destAbs = path.join(targetRoot, AGENTS_DIR_REL, `${agent.id}.md`);
  fs.mkdirSync(path.dirname(destAbs), { recursive: true });
  try {
    fs.lstatSync(destAbs);
    fs.unlinkSync(destAbs);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  fs.writeFileSync(destAbs, buildAgentContent(agent, frameworkPrefix), "utf8");
  return destAbs;
}

function cleanupOrphanAgents(targetRoot, keepIds) {
  const agentsDir = path.join(targetRoot, AGENTS_DIR_REL);
  if (!fs.existsSync(agentsDir)) return [];
  const removed = [];
  for (const name of fs.readdirSync(agentsDir)) {
    if (!/^eversis-.*\.md$/.test(name)) continue;
    if (keepIds.has(name.replace(/\.md$/, ""))) continue;
    const abs = path.join(agentsDir, name);
    let text = "";
    try {
      text = fs.readFileSync(abs, "utf8");
    } catch {
      continue;
    }
    if (!text.includes(GENERATED_MARKER)) continue;
    fs.unlinkSync(abs);
    removed.push(abs);
  }
  return removed;
}

function main() {
  const { outRoot, frameworkPrefix } = parseArgs(process.argv.slice(2));
  const targetRoot = outRoot || findRepoRoot(process.cwd());
  let agents;
  try {
    agents = loadAgentMap();
  } catch (err) {
    if (err instanceof MapError) fail(err.message);
    throw err;
  }
  const written = agents.map((agent) => writeAgent(targetRoot, agent, frameworkPrefix));
  const removed = cleanupOrphanAgents(targetRoot, new Set(agents.map((a) => a.id)));
  console.log(`generated ${written.length} Claude Code role subagent(s):`);
  for (const p of written) {
    console.log(`  ${path.relative(process.cwd(), p) || p}`);
  }
  if (removed.length > 0) {
    console.log(`removed ${removed.length} orphan generated subagent(s):`);
    for (const p of removed) {
      console.log(`  ${path.relative(process.cwd(), p) || p}`);
    }
  }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url))) {
  main();
}
