#!/usr/bin/env node
/**
 * Website docs adapter — prompts generator (TASK: website-docs-skills-prompts-sync).
 * Reads .ai/prompts/{public,internal}/eversis-*.md → writes verbatim copies under
 * website/docs/prompts/{public,internal}/ plus a generated website/docs/prompts/overview.md
 * catalog page (tables built from frontmatter, not hardcoded — counts self-correct).
 * Zero npm dependencies.
 *
 * Usage (repo root):
 *   node adapters/website/generate-prompts.mjs
 *   node adapters/website/generate-prompts.mjs --out /path/to/out
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const GENERATED_MARKER =
  "<!-- GENERATED by adapters/website/generate-prompts.mjs from .ai/prompts/ — do not edit; run `npm run sync:website-docs` -->";

const PROMPT_BUCKETS = ["public", "internal"];

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function findRepoRoot(startDir) {
  let dir = startDir;
  for (;;) {
    if (
      fs.existsSync(path.join(dir, ".ai")) &&
      fs.existsSync(path.join(dir, "adapters"))
    ) {
      return dir;
    }
    const parent = path.dirname(dir);
    if (parent === dir) {
      fail(
        "could not find repository root (expected .ai/ and adapters/). Run from repo root.",
      );
    }
    dir = parent;
  }
}

function parseArgs(argv) {
  let outRoot = null;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) {
        fail("--out requires a directory path");
      }
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot };
}

function stripQuotes(value) {
  if (
    (value.startsWith('"') && value.endsWith('"')) ||
    (value.startsWith("'") && value.endsWith("'"))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

/**
 * Parse the full YAML frontmatter block of a prompt file (flat scalar keys only —
 * matches the shape every .ai/prompts/{public,internal}/*.md file actually uses).
 * @returns {{ meta: Record<string,string>, body: string }}
 */
function parseFrontmatter(text) {
  if (!text.startsWith("---")) fail("prompt file missing frontmatter block");
  const end = text.indexOf("\n---", 3);
  if (end === -1) fail("prompt file frontmatter not terminated");
  const fm = text.slice(3, end);
  const meta = {};
  for (const rawLine of fm.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf(":");
    if (idx === -1) continue;
    const key = line.slice(0, idx).trim();
    const value = stripQuotes(line.slice(idx + 1).trim());
    meta[key] = value;
  }
  return { meta, body: text };
}

function discoverPrompts(repoRoot) {
  const prompts = [];
  for (const bucket of PROMPT_BUCKETS) {
    const dir = path.join(repoRoot, ".ai", "prompts", bucket);
    if (!fs.existsSync(dir)) continue;
    for (const name of fs.readdirSync(dir).sort()) {
      if (!/^eversis-.*\.md$/.test(name)) continue;
      const sourcePath = path.join(dir, name);
      const text = fs.readFileSync(sourcePath, "utf8");
      const { meta } = parseFrontmatter(text);
      for (const required of [
        "title",
        "slug",
        "sidebar_position",
        "prompt_role",
        "prompt_description",
      ]) {
        if (!meta[required]) {
          fail(`${sourcePath}: missing required frontmatter key "${required}"`);
        }
      }
      prompts.push({
        bucket,
        name,
        sourcePath,
        text,
        meta,
        sidebarPosition: Number(meta.sidebar_position),
      });
    }
  }
  return prompts;
}

const GITHUB_REPO_BASE =
  "https://github.com/PiotrNie-Eversis/agent-collections";

/**
 * `.ai/prompts/{public,internal}/` links are written relative to that source location.
 * Two kinds need adjusting once copied into `website/docs/prompts/{public,internal}/`:
 *  - Links into `website/docs/agents/<id>.md` land inside the *destination's own* subtree
 *    once copied — collapse to a docs-relative slug link (`../../agents/<id>`), matching the
 *    convention other website/docs pages already use (e.g. `../agents/overview`).
 *  - Links to anything else at repo root (`AGENTS.md`, `mcp/...`) point *outside* the
 *    Docusaurus docs content root — a relative path can never resolve there (verified via
 *    `website:build`, which flags these as broken regardless of `../` depth). Every other
 *    website/docs page already links to such repo-root paths via absolute GitHub blob/tree
 *    URLs (see e.g. skills/overview.md, integrations/eversis-collections.md) — match that
 *    existing, established convention instead of inventing a new one.
 * This is the one narrow transformation the copy needs — not a general link-rewrite engine.
 */
function rewriteCrossTreeLinks(body) {
  return body
    .replace(
      /\(\.\.\/\.\.\/\.\.\/website\/docs\/agents\/([^)]+?)\.md\)/g,
      "(../../agents/$1)",
    )
    .replace(/\(\.\.\/\.\.\/\.\.\/(?!website\/docs\/agents)([^)]+)\)/g, (_m, target) => {
      const kind = target.endsWith("/") ? "tree" : "blob";
      const cleanTarget = target.endsWith("/") ? target.slice(0, -1) : target;
      return `(${GITHUB_REPO_BASE}/${kind}/main/${cleanTarget})`;
    });
}

function writePromptCopies(prompts, outRoot) {
  for (const prompt of prompts) {
    const destDir = path.join(outRoot, "website", "docs", "prompts", prompt.bucket);
    fs.mkdirSync(destDir, { recursive: true });
    const destPath = path.join(destDir, prompt.name);
    const rewritten = rewriteCrossTreeLinks(prompt.text);
    const content = `${rewritten.replace(/\s+$/, "")}\n\n${GENERATED_MARKER}\n`;
    fs.writeFileSync(destPath, content, "utf8");
  }
}

function buildOverview(prompts) {
  const publicPrompts = prompts
    .filter((p) => p.bucket === "public")
    .sort((a, b) => a.sidebarPosition - b.sidebarPosition);
  const internalPrompts = prompts
    .filter((p) => p.bucket === "internal")
    .sort((a, b) => a.sidebarPosition - b.sidebarPosition);

  const escapeCell = (value) => value.replace(/\|/g, "\\|");
  const row = (p) =>
    `| [${p.name.replace(/\.md$/, "")}](./${p.bucket}/${p.meta.slug}) | ${escapeCell(p.meta.prompt_role)} | ${escapeCell(p.meta.prompt_description)} |`;

  const lines = [
    "---",
    "sidebar_position: 1",
    "title: Prompts Overview",
    "---",
    "",
    "# Prompts Overview",
    "",
    `This framework includes **${publicPrompts.length} public prompts** and **${internalPrompts.length} internal prompts** — Markdown workflow definitions loaded by stable id under **\`.ai/prompts/\`**. **Canonical sources** live under \`.ai/prompts/public/\` and \`.ai/prompts/internal/\` as \`eversis-*.md\` files; the content on this page is copied verbatim from there.`,
    "",
    "**How to invoke — three adapters, not just Cursor:**",
    "",
    "- **Claude Code:** stable prompt id as a slash command (e.g. **`/eversis-implement`**) generated under `.claude/commands/` by the Claude adapter — this is how prompts are triggered outside Cursor.",
    "- **Cursor `@` attachment:** type **`@`** and the file stem (e.g. **`@eversis-implement`**). Cursor resolves the file by name.",
    "- **Cursor `/` project command:** thin `.cursor/commands/eversis-*.md` shims (Cursor adapter) that point back at the SSOT file under `.ai/prompts/`.",
    "",
    "Public prompts are user-facing entry points; internal prompts are delegated to automatically by the Engineering Manager during `/eversis-implement` — you do not attach them directly.",
    "",
    `**Documentation site:** this page and every page under \`prompts/public/\` and \`prompts/internal/\` are **generated** from \`.ai/prompts/**\` by \`node adapters/website/generate-prompts.mjs\` (\`npm run sync:website-docs\`). The generated files are **committed to git** (not gitignored) — same convention as \`.cursor/rules/*.mdc\` and \`.claude/commands/*.md\` under \`adapters/sync.mjs\`. Run \`npm run sync:website-docs:check\` to detect drift; do not hand-edit files under this generated tree — edit the \`.ai/prompts/\` source and regenerate.`,
    "",
    "## Public Prompts",
    "",
    "| Prompt | Role | Description |",
    "| --- | --- | --- |",
    ...publicPrompts.map(row),
    "",
    "## Internal Prompts",
    "",
    "Not invoked directly by users — delegated to automatically during `/eversis-implement` when the workflow requires them.",
    "",
    "| Prompt | Role | Description |",
    "| --- | --- | --- |",
    ...internalPrompts.map(row),
    "",
    "## Input Format",
    "",
    "All prompts accept either:",
    "",
    "- A **Jira ticket ID** (with context attached in chat)",
    "- A **task description** (e.g. add pagination to the user list API)",
    "",
    "The agent adapts based on the input type.",
    "",
    GENERATED_MARKER,
    "",
  ];
  return lines.join("\n");
}

function writeOverview(prompts, outRoot) {
  const destDir = path.join(outRoot, "website", "docs", "prompts");
  fs.mkdirSync(destDir, { recursive: true });
  fs.writeFileSync(path.join(destDir, "overview.md"), buildOverview(prompts), "utf8");
}

function main() {
  const { outRoot } = parseArgs(process.argv.slice(2));
  const repoRoot = findRepoRoot(process.cwd());
  const writeRoot = outRoot || repoRoot;

  const prompts = discoverPrompts(repoRoot);
  if (prompts.length === 0) fail("no prompts discovered under .ai/prompts/");

  writePromptCopies(prompts, writeRoot);
  writeOverview(prompts, writeRoot);

  console.log(
    `website docs: generated ${prompts.length} prompt pages + overview.md`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}

export { discoverPrompts, buildOverview, writePromptCopies, writeOverview, findRepoRoot };
