#!/usr/bin/env node
/**
 * Website docs adapter CLI (TASK: website-docs-skills-prompts-sync).
 * Orchestrates the prompts generator + skills existence/count check.
 * Zero npm dependencies. Mirrors adapters/sync.mjs (write vs --check).
 *
 * Usage (repo root):
 *   node adapters/website/generate.mjs
 *   node adapters/website/generate.mjs --out /path/to/out
 *   node adapters/website/generate.mjs --check
 *   npm run sync:website-docs
 *   npm run sync:website-docs:check
 */

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  discoverPrompts,
  writePromptCopies,
  writeOverview,
  findRepoRoot,
} from "./generate-prompts.mjs";
import { run as runSkillsCheck } from "./check-skills.mjs";

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  let outRoot = null;
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--out") {
      const next = argv[i + 1];
      if (!next || next.startsWith("-")) fail("--out requires a directory path");
      outRoot = path.resolve(next);
      i++;
      continue;
    }
    if (arg === "--check") {
      check = true;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      console.log(
        "Usage: node adapters/website/generate.mjs [--check] [--out <dir>]\n" +
          "  Default: regenerate website/docs/reference/prompts/** from .ai/prompts/**, then run the\n" +
          "           skills existence/count check (informational, non-blocking).\n" +
          "  --check: compare fresh prompt generation to disk (blocking); also runs the\n" +
          "           skills check as blocking. Does not write in-place.\n" +
          "  --out: write/compare prompt output under <dir> (repo-relative tail preserved).\n" +
          "\n" +
          "npm: npm run sync:website-docs | npm run sync:website-docs:check",
      );
      process.exit(0);
    }
    fail(`unknown argument: ${arg}`);
  }
  return { outRoot, check };
}

function normalizeNewlines(text) {
  return text.replace(/^﻿/, "").replace(/\r\n/g, "\n");
}

function walkFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkFiles(full));
    } else {
      out.push(full);
    }
  }
  return out;
}

function runCheck(repoRoot, outRoot) {
  const prompts = discoverPrompts(repoRoot);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "agent-collections-website-sync-"));
  try {
    writePromptCopies(prompts, tmp);
    writeOverview(prompts, tmp);

    const compareRoot = outRoot || repoRoot;
    const expectedRoot = path.join(tmp, "website", "docs", "reference", "prompts");
    const actualRoot = path.join(compareRoot, "website", "docs", "reference", "prompts");
    const drifts = [];

    const expectedFiles = fs.existsSync(expectedRoot) ? walkFiles(expectedRoot) : [];
    for (const expectedPath of expectedFiles) {
      const rel = path.relative(expectedRoot, expectedPath);
      const actualPath = path.join(actualRoot, rel);
      if (!fs.existsSync(actualPath)) {
        drifts.push(`missing on disk: website/docs/reference/prompts/${rel}`);
        continue;
      }
      const expected = normalizeNewlines(fs.readFileSync(expectedPath, "utf8"));
      const actual = normalizeNewlines(fs.readFileSync(actualPath, "utf8"));
      if (expected !== actual) {
        drifts.push(`drift: website/docs/reference/prompts/${rel}`);
      }
    }

    const actualFiles = fs.existsSync(actualRoot) ? walkFiles(actualRoot) : [];
    const expectedRelSet = new Set(expectedFiles.map((f) => path.relative(expectedRoot, f)));
    for (const actualPath of actualFiles) {
      const rel = path.relative(actualRoot, actualPath);
      if (expectedRelSet.has(rel)) continue;
      const text = fs.readFileSync(actualPath, "utf8");
      if (!text.includes("GENERATED by adapters/website/generate-prompts.mjs")) continue;
      drifts.push(`unexpected generated file on disk: website/docs/reference/prompts/${rel}`);
    }

    if (drifts.length > 0) {
      console.error("error: website docs prompt drift detected:");
      for (const d of drifts) console.error(`  ${d}`);
      console.error("hint: run `npm run sync:website-docs` then re-check.");
      process.exit(1);
    }

    console.log("website docs prompts check: OK (no drift)");
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }

  const skillsOk = runSkillsCheck(repoRoot);
  if (!skillsOk) process.exit(1);
}

function runWrite(repoRoot, outRoot) {
  const prompts = discoverPrompts(repoRoot);
  const writeRoot = outRoot || repoRoot;
  writePromptCopies(prompts, writeRoot);
  writeOverview(prompts, writeRoot);
  console.log(`website docs: generated ${prompts.length} prompt pages + overview.md`);

  runSkillsCheck(repoRoot);
}

function main() {
  const { outRoot, check } = parseArgs(process.argv.slice(2));
  const repoRoot = findRepoRoot(process.cwd());

  if (check) {
    runCheck(repoRoot, outRoot);
  } else {
    runWrite(repoRoot, outRoot);
  }
}

main();
