#!/usr/bin/env bash
# lib/setup-agent-collections/legacy-pi.sh — hand-ported Pi setups.
#
# Some projects ran Pi before the framework had a Pi adapter: a consumer script
# (scripts/gen-pi-adapter.mjs + scripts/pi-rule-map.yaml, run by `sync:agents`
# package.json scripts) wrote a framework-shaped .pi/ tree with its own marker.
# The installer cannot tell that tree from "Pi was deselected", so a plain
# --upgrade / --sync would prune part of it and leave the rest stale, and the
# old generator would later revert the upgrade. Two read-only checks run right
# after load_selection_or_fail, before any write:
#   1. check_pi_hand_port_or_stop — stops (exit 1) the one ambiguous case and
#      prints both explicit ways forward.
#   2. report_legacy_pi_generator — warn-only list of legacy generator files
#      and scripts to remove; print_summary repeats it (LEGACY_PI_FINDINGS)
#      and recounts the legacy-marked .pi/ files after the Pi stage
#      (LEGACY_PI_MARKED_AT_START holds the count from the start of the run).
#
# Sourced by setup-agent-collections.sh after link-framework.sh (uses
# PI_GENERATED_MARKER). Bash 3.2 compatible.

# Marker the legacy consumer generator put in every .pi/ file it wrote
# (consumer projects that hand-ported Pi before the framework shipped a Pi adapter).
readonly LEGACY_PI_MARKER="GENERATED by scripts/gen-pi-adapter.mjs"

# Newline-separated findings of report_legacy_pi_generator, printed again by
# print_summary. Start empty so a stray value in the caller's env never shows.
LEGACY_PI_FINDINGS=""

# Number of legacy-marked .pi/ files report_legacy_pi_generator counted at the
# start of the run. print_summary compares it with a recount after the Pi
# stage to say whether they were migrated. Start empty, same guard as above.
LEGACY_PI_MARKED_AT_START=""

# Prints, one per line and relative to TARGET_DIR, the .pi/ files that carry the
# legacy marker. *.pre-agent-collections*.bak copies are skipped: the Pi
# generator writes them on purpose when it replaces a hand-made file, and
# counting them would report (and stop) forever after a migration. The skill
# backups under .pi/pre-agent-collections-backup/ (link-framework.sh) are
# skipped for the same reason: a backed-up legacy skill keeps the marker.
# The TARGET_DIR prefix is stripped as plain text, never as a regex.
_legacy_pi_marked_files() {
  local pi_dir="${TARGET_DIR}/.pi" path
  [[ -d "$pi_dir" ]] || return 0
  while IFS= read -r path; do
    [[ -n "$path" ]] || continue
    printf '%s\n' "${path#"$TARGET_DIR"/}"
  done <<< "$(grep -rlF --exclude='*.bak' --exclude-dir='pre-agent-collections-backup' \
    "$LEGACY_PI_MARKER" "$pi_dir" 2>/dev/null || true)"
}

# Prints, one per line and relative to TARGET_DIR, the framework-shaped .pi/
# entries that the framework did not write: .pi/skills/eversis-* mirror entries
# (not eversis-rule-*) and .pi/prompts/eversis-*.md without the framework
# marker. With pi unselected, these are what _prune_deselected_pi would remove
# (skills, by name) or leave stale (prompts) — see check_pi_hand_port_or_stop.
_pi_unmarked_framework_shaped() {
  local pi_dir="${TARGET_DIR}/.pi" entry name
  [[ -d "$pi_dir" ]] || return 0
  for entry in "${pi_dir}/skills"/eversis-*; do
    [[ -e "$entry" ]] || [[ -L "$entry" ]] || continue
    name="$(basename "$entry")"
    case "$name" in
      eversis-rule-*) continue ;;
    esac
    printf '%s\n' ".pi/skills/${name}"
  done
  for entry in "${pi_dir}/prompts"/eversis-*.md; do
    [[ -f "$entry" ]] || continue
    grep -qF "$PI_GENERATED_MARKER" "$entry" 2>/dev/null && continue
    printf '%s\n' ".pi/prompts/$(basename "$entry")"
  done
}

# Prints the command that runs this installer, as the person types it in the
# project root, for the stop message below. Every path check uses resolved
# paths: SCRIPT_DIR is logical (pwd) while TARGET_DIR from git rev-parse is
# physical (macOS /var vs /private/var, symlinked project folders).
#   - Inside the project (relative-path.mjs, realpath on both sides, from
#     TARGET_DIR to the script succeeds with no leading ../ and no absolute
#     path): the project-relative path, for example
#     bash vendor/agent-collections/scripts/setup-agent-collections.sh.
#   - Otherwise, when AGENT_COLLECTIONS_HOME resolves to the framework folder
#     that holds this script: bash "$AGENT_COLLECTIONS_HOME/scripts/…", left
#     for the person's shell to expand.
#   - Otherwise, and also when node or relative-path.mjs fails: the quoted
#     absolute path of the running script.
_installer_command() {
  local script_dir="${SETUP_SCRIPT_DIR:-}"
  if [[ -z "$script_dir" ]]; then
    printf '%s' "bash scripts/setup-agent-collections.sh"
    return 0
  fi
  local script="${script_dir}/setup-agent-collections.sh" rel=""
  if [[ -n "${LIB_DIR:-}" ]] && command -v node >/dev/null 2>&1; then
    rel="$(node "${LIB_DIR}/relative-path.mjs" "$TARGET_DIR" "$script" 2>/dev/null)" || rel=""
  fi
  case "$rel" in
    ""|..|../*|/*) ;;
    *)
      if [[ "$rel" =~ ^[A-Za-z0-9._/+-]+$ ]]; then
        printf 'bash %s' "$rel"
      else
        printf 'bash "%s"' "$(_shell_dq_escape "$rel")"
      fi
      return 0
      ;;
  esac
  if [[ -n "${AGENT_COLLECTIONS_HOME:-}" ]]; then
    local home_real framework_real
    home_real="$(cd -P "${AGENT_COLLECTIONS_HOME}" 2>/dev/null && pwd -P)" || home_real=""
    framework_real="$(cd -P "${script_dir}/.." 2>/dev/null && pwd -P)" || framework_real=""
    if [[ -n "$home_real" ]] && [[ "$home_real" == "$framework_real" ]]; then
      # shellcheck disable=SC2016
      printf '%s' 'bash "$AGENT_COLLECTIONS_HOME/scripts/setup-agent-collections.sh"'
      return 0
    fi
  fi
  printf 'bash "%s"' "$(_shell_dq_escape "$script")"
}

# Prints $1 escaped for use inside double quotes in a shell command:
# backslash, double quote, dollar sign and backtick get a backslash.
_shell_dq_escape() {
  printf '%s' "$1" | sed 's/[\\"$`]/\\&/g'
}

# Prints the "Found" lines of the stop message from the evidence lines in $1.
# A file line under a listed .pi/skills/<name> entry is dropped, so one skill
# takes one line. Then the .pi/skills/eversis-* lines come first and the other
# lines after, each group sorted, so the skills are never hidden behind the
# 5-line limit of the message.
_pi_hand_port_found_lines() {
  local all line rest name skills="" others="" nl=$'\n'
  all="$(printf '%s\n' "$1" | LC_ALL=C sort -u)"
  while IFS= read -r line; do
    [[ -n "$line" ]] || continue
    case "$line" in
      .pi/skills/*/*)
        rest="${line#.pi/skills/}"
        name="${rest%%/*}"
        # Whole-line, literal match (the quoted part of a pattern is literal).
        if [[ "${nl}${all}${nl}" == *"${nl}.pi/skills/${name}${nl}"* ]]; then
          continue
        fi
        ;;
    esac
    case "$line" in
      .pi/skills/eversis-*) skills="${skills}${line}
" ;;
      *) others="${others}${line}
" ;;
    esac
  done <<< "$all"
  printf '%s%s' "$skills" "$others"
}

# AC1: --upgrade / --sync without an explicit --agents, pi not selected, and a
# hand-ported .pi/ on disk. The record alone cannot say whether the person
# dropped Pi or never installed it through the framework, and either guess
# loses work (prune a working hand port, or silently rewrite ~30 files). So
# stop before run_vendor_setup and anything else writes, and name both
# commands with the agents this run would have used. An explicit --agents is a
# choice the person made and keeps today's behaviour (migrate or deselect).
# Both commands start with the installer path from _installer_command, so they
# work when pasted in the project root: project-relative when the installer is
# inside the project, "$AGENT_COLLECTIONS_HOME/…" when that names this
# framework, else the quoted absolute path. "Found" lists the skill entries
# first (_pi_hand_port_found_lines).
check_pi_hand_port_or_stop() {
  [[ "${ARG_UPGRADE:-false}" == "true" ]] || [[ "${ARG_SYNC:-false}" == "true" ]] || return 0
  [[ -z "${ARG_AGENTS:-}" ]] || return 0
  case ",${SELECTED_AGENTS:-}," in
    *,pi,*) return 0 ;;
  esac
  [[ -d "${TARGET_DIR}/.pi" ]] || return 0

  local evidence=""
  evidence="$(_legacy_pi_marked_files; _pi_unmarked_framework_shaped)"
  [[ -n "$evidence" ]] || return 0

  # Same fallback as the rest of the installer: an empty selection means cursor.
  local current="${SELECTED_AGENTS:-cursor}"
  local installer
  installer="$(_installer_command)"
  local shown="" count=0 line
  while IFS= read -r line; do
    [[ -n "$line" ]] || continue
    count=$((count + 1))
    if [[ "$count" -le 5 ]]; then
      shown="${shown}
    ${line}"
    fi
  done <<< "$(_pi_hand_port_found_lines "$evidence")"
  if [[ "$count" -gt 5 ]]; then
    shown="${shown}
    … and $((count - 5)) more"
  fi

  die "Stopped before any change: .pi/ holds a Pi setup the framework did not generate, and pi is not in the selection (${current}).
  Found:${shown}
  An upgrade without --agents would remove part of it and leave the rest stale. Choose one and re-run:
    Migrate to the framework Pi adapter (the Pi generator copies each hand-made file it replaces to *.pre-agent-collections.bak;
    .pi/skills/eversis-* entries that match the installer's recorded copy are replaced without a backup; the other entries
    that are not identical framework copies are copied to .pi/pre-agent-collections-backup/skills/, then replaced by the
    framework skills mirror):
      ${installer} --upgrade --sync --agents ${current},pi
    Keep Pi out of the framework (removes framework Pi files and every .pi/skills/eversis-* entry — entries that match the
    installer's recorded copy are removed without a backup; the other entries that are not identical framework copies are
    copied to .pi/pre-agent-collections-backup/skills/ first; other hand-made files stay):
      ${installer} --upgrade --sync --agents ${current}"
}

# AC3: warn-only report of a legacy Pi generator in the consumer project. Its
# `sync:agents` script would otherwise regenerate the old .pi/ tree after this
# upgrade (and, through a symlinked .pi/skills mirror, write into the framework
# copy). Only reads files; never runs a consumer script. A missing or invalid
# package.json is not an error. Findings go to LEGACY_PI_FINDINGS for the summary;
# the legacy-marked file count from this start of the run goes to
# LEGACY_PI_MARKED_AT_START.
report_legacy_pi_generator() {
  LEGACY_PI_FINDINGS=""
  LEGACY_PI_MARKED_AT_START=""
  local findings="" rel
  for rel in scripts/gen-pi-adapter.mjs scripts/pi-rule-map.yaml; do
    if [[ -e "${TARGET_DIR}/${rel}" ]]; then
      findings="${findings}${rel}
"
    fi
  done

  local pkg="${TARGET_DIR}/package.json" scripts_found=""
  if [[ -f "$pkg" ]] && command -v node >/dev/null 2>&1; then
    scripts_found="$(node -e '
      let j;
      try { j = JSON.parse(require("fs").readFileSync(process.argv[1], "utf8")); } catch { process.exit(0); }
      const s = j && typeof j.scripts === "object" && j.scripts ? j.scripts : {};
      for (const [name, cmd] of Object.entries(s)) {
        const c = String(cmd);
        if (name.startsWith("sync:agents") || c.includes("gen-pi-adapter") || c.includes("pi-rule-map")) {
          console.log("package.json script \"" + name + "\": " + c);
        }
      }
    ' "$pkg" 2>/dev/null)" || scripts_found=""
    if [[ -n "$scripts_found" ]]; then
      findings="${findings}${scripts_found}
"
    fi
  fi

  # The marked-file count is part of the warning below but not of
  # LEGACY_PI_FINDINGS: the Pi stage may still migrate or remove those files,
  # so only the start count is kept and print_summary recounts.
  local marked_count marked_line="" nl=$'\n'
  marked_count="$(_legacy_pi_marked_files | grep -c . || true)"
  LEGACY_PI_MARKED_AT_START="${marked_count:-0}"
  if [[ "${marked_count:-0}" -gt 0 ]]; then
    marked_line="${marked_count} .pi/ file(s) still carry the legacy marker \"${LEGACY_PI_MARKER}\""
  fi

  LEGACY_PI_FINDINGS="${findings%$'\n'}"
  [[ -n "$LEGACY_PI_FINDINGS" ]] || [[ -n "$marked_line" ]] || return 0
  log_warn "Legacy Pi generator found (it would undo this install on its next run):"
  while IFS= read -r rel; do
    [[ -n "$rel" ]] || continue
    log_warn "  - ${rel}"
  done <<< "${LEGACY_PI_FINDINGS}${LEGACY_PI_FINDINGS:+${nl}}${marked_line}"
  log_warn "Remove the files and package.json scripts above; setup-agent-collections.sh --upgrade --sync replaces them."
  log_warn "Find remaining references with: git grep -nE \"sync:agents|gen-pi-adapter|pi-rule-map\""
  return 0
}
