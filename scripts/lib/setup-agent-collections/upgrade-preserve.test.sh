#!/usr/bin/env bash
# upgrade-preserve.test.sh — AC-99: --upgrade / --sync selection resolution
# (per-field flag override, marker-gated agent detection, MCP preserve flag)
# without Docker. Sources upgrade.sh directly, like selection-ssot.test.sh.
#
# Usage (from repo root):
#   bash scripts/lib/setup-agent-collections/upgrade-preserve.test.sh

set -euo pipefail

LIB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${LIB_DIR}/../../.." && pwd)"

PASS=0
FAIL=0

_pass() { echo "  ✓ $1"; PASS=$(( PASS + 1 )); }
_fail() { echo "  ✗ $1"; FAIL=$(( FAIL + 1 )); exit 1; }

_check() {
  local label="$1" actual="$2" expected="$3"
  if [[ "$actual" == "$expected" ]]; then
    _pass "$label"
  else
    echo "      expected: '${expected}'"
    echo "      actual:   '${actual}'"
    _fail "$label"
  fi
}

TARGET_DIR="$(mktemp -d)"
COLLECTIONS_HOME="$REPO_ROOT"
trap 'rm -rf "$TARGET_DIR"' EXIT

# shellcheck source=common.sh
source "${LIB_DIR}/common.sh"
# shellcheck source=upgrade.sh
source "${LIB_DIR}/upgrade.sh"
# shellcheck source=link-framework.sh
source "${LIB_DIR}/link-framework.sh"

CLAUDE_MARKER='<!-- GENERATED by adapters/claude/generate.mjs — do not edit; re-run the generator -->'
CLAUDE_CMD_MARKER='<!-- GENERATED by adapters/claude/generate-commands.mjs — do not edit; re-run the generator -->'
CURSOR_MARKER='<!-- GENERATED by adapters/cursor/generate.mjs — do not edit; re-run the generator -->'

# Fresh target with a record listing $1 agents / $2 MCP ids / $3 profile
# (JSON array bodies), and every flag cleared — the state an
# `--upgrade --sync --non-interactive` run starts from.
_reset() {
  local agents_json="$1" mcp_json="$2" profile="${3:-frontend}"
  rm -rf "${TARGET_DIR:?}"/* "${TARGET_DIR:?}"/.[!.]* 2>/dev/null || true
  mkdir -p "${TARGET_DIR}/.agent-collections"
  cat > "${TARGET_DIR}/.agent-collections/install-selection.json" <<EOF
{
  "frameworkVersion": "0.0.0-test",
  "agents": [${agents_json}],
  "mcpServers": [${mcp_json}],
  "domainProfile": "${profile}",
  "vendorMode": "local",
  "linkMode": "copy"
}
EOF
  unset SELECTED_AGENTS MCP_SELECTED_IDS DOMAIN_PROFILE MCP_PRESERVE_EXISTING MCP_CONFIGURED_SERVERS 2>/dev/null || true
  ARG_AGENTS=""
  ARG_MCP_SERVERS=""
  ARG_PROFILE=""
  ARG_SSOT_SOURCE=""
  ARG_SSOT_SOURCE_PASSED="false"
  ARG_CONFLUENCE_SPACE_KEY=""
  ARG_CONFLUENCE_SPACE_KEY_PASSED="false"
  ARG_VENDOR=""
  ARG_VENDOR_PASSED="false"
  ARG_LINK_MODE="auto"
  ARG_LINK_MODE_PASSED="false"
}

echo "upgrade-preserve unit tests"
echo ""

# S1: hand-written CLAUDE.md is not evidence — Claude stays off.
_reset '"cursor"' '"eversis-collections"'
printf '# My project notes\n\nHand-written.\n' > "${TARGET_DIR}/CLAUDE.md"
load_selection_or_fail >/dev/null
_check "S1 hand-written CLAUDE.md does not enable claude" "$SELECTED_AGENTS" "cursor"

# S4: framework-generated CLAUDE.md keeps Claude even when the record lacks it.
_reset '"cursor"' '"eversis-collections"'
printf '# Agent Collections (Claude Code)\n\n%s\n' "$CLAUDE_MARKER" > "${TARGET_DIR}/CLAUDE.md"
load_selection_or_fail >/dev/null
_check "S4 generated CLAUDE.md keeps claude" "$SELECTED_AGENTS" "cursor,claude"

# Generated .claude/commands only (no root CLAUDE.md) is evidence too.
_reset '"cursor"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.claude/commands"
printf '%s\n\n# eversis-implement\n' "$CLAUDE_CMD_MARKER" > "${TARGET_DIR}/.claude/commands/eversis-implement.md"
load_selection_or_fail >/dev/null
_check "generated .claude/commands/eversis-*.md alone keeps claude" "$SELECTED_AGENTS" "cursor,claude"

# A non-generated .claude/commands/eversis-*.md is not evidence.
_reset '"cursor"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.claude/commands"
printf '# eversis-mine\n\nHand-written command.\n' > "${TARGET_DIR}/.claude/commands/eversis-mine.md"
load_selection_or_fail >/dev/null
_check "hand-written .claude/commands/eversis-*.md does not enable claude" "$SELECTED_AGENTS" "cursor"

# Cursor: generated .cursor/commands with a claude-only record → cursor kept.
_reset '"claude"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.cursor/commands"
printf '# eversis-implement\n\n%s\n' "$CURSOR_MARKER" > "${TARGET_DIR}/.cursor/commands/eversis-implement.md"
load_selection_or_fail >/dev/null
_check "generated .cursor/commands/eversis-*.md keeps cursor" "$SELECTED_AGENTS" "claude,cursor"

# Cursor: generated .cursor/rules/eversis-*.mdc is evidence as well.
_reset '"claude"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.cursor/rules"
printf -- '---\ndescription: x\n---\n%s\n' "$CURSOR_MARKER" > "${TARGET_DIR}/.cursor/rules/eversis-agent-core.mdc"
load_selection_or_fail >/dev/null
_check "generated .cursor/rules/eversis-*.mdc keeps cursor" "$SELECTED_AGENTS" "claude,cursor"

# Project-owned eversis-project-stack.mdc (no marker) is not evidence.
_reset '"claude"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.cursor/rules"
printf -- '---\ndescription: stack\n---\n# Project stack\n' > "${TARGET_DIR}/.cursor/rules/eversis-project-stack.mdc"
load_selection_or_fail >/dev/null
_check "project-owned eversis-project-stack.mdc does not enable cursor" "$SELECTED_AGENTS" "claude"

# S2: explicit --agents with spaces replaces the record (and skips detection).
_reset '"cursor"' '"eversis-collections"'
printf '# Agent Collections (Claude Code)\n\n%s\n' "$CLAUDE_MARKER" > "${TARGET_DIR}/CLAUDE.md"
ARG_AGENTS="cursor, claude"
load_selection_or_fail >/dev/null
_check "S2 --agents='cursor, claude' is space-stripped" "$SELECTED_AGENTS" "cursor,claude"

_reset '"cursor","claude"' '"eversis-collections"'
printf '# Agent Collections (Claude Code)\n\n%s\n' "$CLAUDE_MARKER" > "${TARGET_DIR}/CLAUDE.md"
ARG_AGENTS="cursor"
load_selection_or_fail >/dev/null
_check "explicit --agents=cursor deselects claude despite generated CLAUDE.md" "$SELECTED_AGENTS" "cursor"

# Explicit --mcp-servers (with spaces) replaces the record; preserve off.
_reset '"cursor"' '"eversis-collections","atlassian"'
ARG_MCP_SERVERS="context7, eversis-collections"
load_selection_or_fail >/dev/null
_check "--mcp-servers='context7, eversis-collections' is space-stripped" "$MCP_SELECTED_IDS" "context7,eversis-collections"
_check "--mcp-servers sets MCP_PRESERVE_EXISTING=false" "$MCP_PRESERVE_EXISTING" "false"
_check "--mcp-servers keeps MCP_CONFIGURED_SERVERS equal to the selection" "$MCP_CONFIGURED_SERVERS" "context7,eversis-collections"

# No MCP flag: record ids, preserve on.
_reset '"cursor"' '"eversis-collections","atlassian"'
load_selection_or_fail >/dev/null
_check "no --mcp-servers keeps recorded MCP ids" "$MCP_SELECTED_IDS" "eversis-collections,atlassian"
_check "no --mcp-servers sets MCP_PRESERVE_EXISTING=true" "$MCP_PRESERVE_EXISTING" "true"

# Catalog ids found only in host MCP files are never added to the selection
# (preserved on disk by mcp-merge.mjs, not written back to the record).
_reset '"cursor","claude"' '"eversis-collections"'
mkdir -p "${TARGET_DIR}/.cursor"
printf '{"mcpServers":{"eversis-collections":{},"context7":{}}}\n' > "${TARGET_DIR}/.cursor/mcp.json"
printf '{"mcpServers":{"eversis-collections":{},"atlassian":{}}}\n' > "${TARGET_DIR}/.mcp.json"
load_selection_or_fail >/dev/null
_check "catalog ids present only in .cursor/mcp.json / .mcp.json are not added to MCP_SELECTED_IDS" "$MCP_SELECTED_IDS" "eversis-collections"
_check "MCP_CONFIGURED_SERVERS stays equal to the selection" "$MCP_CONFIGURED_SERVERS" "eversis-collections"

# --profile overrides the record; omitted keeps it.
_reset '"cursor"' '"eversis-collections"' "frontend"
ARG_PROFILE="backend"
load_selection_or_fail >/dev/null
_check "--profile=backend overrides recorded frontend" "$DOMAIN_PROFILE" "backend"

_reset '"cursor"' '"eversis-collections"' "frontend"
load_selection_or_fail >/dev/null
_check "omitted --profile keeps recorded profile" "$DOMAIN_PROFILE" "frontend"

# Review S1: --vendor / --link-mode follow the per-field contract. The record
# from _reset has vendorMode "local" and linkMode "copy".
_reset '"cursor"' '"eversis-collections"'
load_selection_or_fail >/dev/null
_check "omitted --vendor keeps recorded local mode (VENDOR_MODE)" "$VENDOR_MODE" ""
_check "omitted --vendor keeps recorded local mode (ARG_VENDOR)" "$ARG_VENDOR" ""
_check "omitted --link-mode (default auto) keeps recorded linkMode" "$ARG_LINK_MODE" "copy"

_reset '"cursor"' '"eversis-collections"'
ARG_VENDOR="submodule"
ARG_VENDOR_PASSED="true"
ARG_LINK_MODE="symlink"
ARG_LINK_MODE_PASSED="true"
load_selection_or_fail >/dev/null
_check "explicit --vendor=submodule overrides recorded vendorMode" "$VENDOR_MODE" "submodule"
_check "explicit --vendor leaves ARG_VENDOR as passed" "$ARG_VENDOR" "submodule"
_check "explicit --link-mode=symlink overrides recorded linkMode" "$ARG_LINK_MODE" "symlink"

# Review B1: an explicit Cursor deselect prunes marker-bearing generated
# .cursor/commands / .cursor/rules files, keeps the project-owned stack rule
# and unmarked files — so the next --upgrade no longer re-detects Cursor.
_seed_cursor_surfaces() {
  mkdir -p "${TARGET_DIR}/.cursor/commands" "${TARGET_DIR}/.cursor/rules"
  printf '# eversis-implement\n\n%s\n' "$CURSOR_MARKER" > "${TARGET_DIR}/.cursor/commands/eversis-implement.md"
  printf -- '---\ndescription: x\n---\n%s\n' "$CURSOR_MARKER" > "${TARGET_DIR}/.cursor/rules/eversis-agent-core.mdc"
  printf -- '---\ndescription: stack\n---\n# Project stack\n' > "${TARGET_DIR}/.cursor/rules/eversis-project-stack.mdc"
  printf '# eversis-mine\n\nHand-written.\n' > "${TARGET_DIR}/.cursor/commands/eversis-mine.md"
  printf -- '---\ndescription: mine\n---\n# mine\n' > "${TARGET_DIR}/.cursor/rules/eversis-mine.mdc"
}

_reset '"claude"' '"eversis-collections"'
_seed_cursor_surfaces
SELECTED_AGENTS="cursor,claude"
_prune_deselected_cursor_generated >/dev/null
if [[ -f "${TARGET_DIR}/.cursor/commands/eversis-implement.md" ]] && \
   [[ -f "${TARGET_DIR}/.cursor/rules/eversis-agent-core.mdc" ]]; then
  _pass "cursor selected: generated .cursor files are not pruned"
else
  _fail "cursor selected: generated .cursor files are not pruned"
fi
# Before the prune, a claude-only record would re-detect Cursor (the B1 bug).
unset SELECTED_AGENTS
load_selection_or_fail >/dev/null
_check "B1 precondition: generated .cursor files re-select cursor on upgrade" "$SELECTED_AGENTS" "claude,cursor"

SELECTED_AGENTS="claude"
_prune_deselected_cursor_generated >/dev/null
if [[ ! -e "${TARGET_DIR}/.cursor/commands/eversis-implement.md" ]] && \
   [[ ! -e "${TARGET_DIR}/.cursor/rules/eversis-agent-core.mdc" ]]; then
  _pass "cursor deselected: marker-bearing .cursor/commands and .cursor/rules files pruned"
else
  _fail "cursor deselected: marker-bearing .cursor/commands and .cursor/rules files pruned"
fi
if [[ -f "${TARGET_DIR}/.cursor/rules/eversis-project-stack.mdc" ]] && \
   [[ -f "${TARGET_DIR}/.cursor/commands/eversis-mine.md" ]] && \
   [[ -f "${TARGET_DIR}/.cursor/rules/eversis-mine.mdc" ]]; then
  _pass "cursor deselected: eversis-project-stack.mdc and unmarked files kept"
else
  _fail "cursor deselected: eversis-project-stack.mdc and unmarked files kept"
fi
unset SELECTED_AGENTS
load_selection_or_fail >/dev/null
_check "B1: after the prune, the next upgrade keeps the record (no cursor re-detect)" "$SELECTED_AGENTS" "claude"
_check "B1: detect_installed_agents no longer finds cursor" "$(detect_installed_agents)" ""

# Claude call sites of _prune_marker_gated_dir keep their default glob/log.
mkdir -p "${TARGET_DIR}/.claude/commands"
printf '%s\n' "$CLAUDE_CMD_MARKER" > "${TARGET_DIR}/.claude/commands/eversis-implement.md"
_claude_log="$(_prune_marker_gated_dir "${TARGET_DIR}/.claude/commands" \
  "GENERATED by adapters/claude/generate-commands.mjs" ".claude/commands/*.md")"
if [[ ! -e "${TARGET_DIR}/.claude/commands/eversis-implement.md" ]] && \
   echo "$_claude_log" | grep -qF '(Claude not in --agents)'; then
  _pass "_prune_marker_gated_dir defaults unchanged for Claude call sites"
else
  _fail "_prune_marker_gated_dir defaults unchanged for Claude call sites"
fi

# Generator safety net (Gap 6): adapters/claude/generate.mjs backs up a
# marker-less root CLAUDE.md before regenerating it. Runs with cwd = repo root
# (findRepoRoot) and --out pointing at a scratch dir.
GEN_OUT="$(mktemp -d)"
trap 'rm -rf "$TARGET_DIR" "$GEN_OUT"' EXIT
_run_claude_generator() {
  (cd "$REPO_ROOT" && node adapters/claude/generate.mjs --out "$GEN_OUT") >/dev/null 2>&1
}

printf '# Team notes\n\nHand-written, keep me.\n' > "${GEN_OUT}/CLAUDE.md"
cp "${GEN_OUT}/CLAUDE.md" "${GEN_OUT}/original.md"
_run_claude_generator
if [[ -f "${GEN_OUT}/CLAUDE.md.pre-agent-collections.bak" ]] && \
   cmp -s "${GEN_OUT}/original.md" "${GEN_OUT}/CLAUDE.md.pre-agent-collections.bak"; then
  _pass "hand-written CLAUDE.md is copied to CLAUDE.md.pre-agent-collections.bak"
else
  _fail "hand-written CLAUDE.md is copied to CLAUDE.md.pre-agent-collections.bak"
fi
if grep -qF 'GENERATED by adapters/claude/generate.mjs' "${GEN_OUT}/CLAUDE.md"; then
  _pass "regenerated CLAUDE.md carries the generator marker"
else
  _fail "regenerated CLAUDE.md carries the generator marker"
fi

# Marker-bearing CLAUDE.md (the file just generated) → no new backup.
rm -f "${GEN_OUT}/CLAUDE.md.pre-agent-collections.bak"
_run_claude_generator
if ! ls "${GEN_OUT}"/CLAUDE.md.pre-agent-collections*.bak >/dev/null 2>&1; then
  _pass "generator-owned CLAUDE.md is regenerated without a backup"
else
  _fail "generator-owned CLAUDE.md is regenerated without a backup"
fi

# A differing older backup is never overwritten — a timestamped one is added.
printf 'older backup\n' > "${GEN_OUT}/CLAUDE.md.pre-agent-collections.bak"
printf '# Second hand-written version\n' > "${GEN_OUT}/CLAUDE.md"
_run_claude_generator
_stamped="$(ls "${GEN_OUT}"/CLAUDE.md.pre-agent-collections.*.bak 2>/dev/null | grep -v '/CLAUDE.md.pre-agent-collections.bak$' || true)"
if [[ "$(cat "${GEN_OUT}/CLAUDE.md.pre-agent-collections.bak")" == "older backup" ]] && \
   [[ -n "$_stamped" ]] && [[ "$(cat "$_stamped")" == "# Second hand-written version" ]]; then
  _pass "differing existing .bak kept; new backup gets a timestamped name"
else
  _fail "differing existing .bak kept; new backup gets a timestamped name"
fi

# Review S3: a symlinked CLAUDE.md (e.g. -> AGENTS.md) is generator-owned
# territory — no backup, target untouched, link replaced by a regular file.
rm -f "${GEN_OUT}"/CLAUDE.md* "${GEN_OUT}/AGENTS.md"
printf '# AGENTS\n\nShared orientation map.\n' > "${GEN_OUT}/AGENTS.md"
cp "${GEN_OUT}/AGENTS.md" "${GEN_OUT}/agents-original.md"
ln -s AGENTS.md "${GEN_OUT}/CLAUDE.md"
_run_claude_generator
if ! ls "${GEN_OUT}"/CLAUDE.md.pre-agent-collections*.bak >/dev/null 2>&1; then
  _pass "symlinked CLAUDE.md: no backup created"
else
  _fail "symlinked CLAUDE.md: no backup created"
fi
if cmp -s "${GEN_OUT}/AGENTS.md" "${GEN_OUT}/agents-original.md"; then
  _pass "symlinked CLAUDE.md: link target content unchanged"
else
  _fail "symlinked CLAUDE.md: link target content unchanged"
fi
if [[ ! -L "${GEN_OUT}/CLAUDE.md" ]] && [[ -f "${GEN_OUT}/CLAUDE.md" ]] && \
   grep -qF 'GENERATED by adapters/claude/generate.mjs' "${GEN_OUT}/CLAUDE.md"; then
  _pass "symlinked CLAUDE.md: replaced by a generated regular file"
else
  _fail "symlinked CLAUDE.md: replaced by a generated regular file"
fi

echo ""
echo "  ✅  All ${PASS} upgrade-preserve unit tests passed."
