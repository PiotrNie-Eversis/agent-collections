}

_run_adapter_sync() {
  require_cmd node "Install Node.js ≥ 18 from https://nodejs.org"
  local sync_mjs="${COLLECTIONS_HOME}/adapters/sync.mjs"
  [[ -f "$sync_mjs" ]] || die "Missing adapters/sync.mjs in framework home."

  local agents_csv="${SELECTED_AGENTS:-cursor}"
  local args=(--out "${TARGET_DIR}" --agents "${agents_csv}")

  local framework_prefix
  framework_prefix="$(_resolve_framework_prefix)"
  if [[ -n "$framework_prefix" ]]; then
    args+=(--framework-prefix "$framework_prefix")
  fi

  log_info "Running adapter sync → ${TARGET_DIR} (agents: ${agents_csv}) …"
  (cd "$COLLECTIONS_HOME" && node "$sync_mjs" "${args[@]}") \
    || die "adapters/sync.mjs failed."
  log_ok "Adapter sync complete."
}

link_framework_files() {
  local link_mode="${ARG_LINK_MODE:-auto}"
  if [[ "$link_mode" == "auto" ]]; then
    if [[ "$OS_TYPE" == "windows" ]]; then
      link_mode="copy"
    else
      link_mode="symlink"
    fi
  fi
  EFFECTIVE_LINK_MODE="$link_mode"
  export EFFECTIVE_LINK_MODE

  mkdir -p "${TARGET_DIR}/.cursor/rules"

  # Skills are mirrored into <agent>/skills/ for both Claude and Cursor
  # (docs/specs/promote-skill-cursor-packaging/) — a real local fallback file,
  # not a vendor-specific "Agent Skills" UI registration. Prompts/commands are
  # NOT mirrored as a second copy: .cursor/commands/*.md is the generated
  # adapter output itself (adapters/cursor/generate.mjs, with a vendor-path-
  # corrected SSOT pointer via --framework-prefix), so no separate mirror step
  # is needed for those.
  # Align a clean submodule pin to INSTALLER_FRAMEWORK_HOME when vendored
  # sync.mjs would reject flags this launched installer will pass.
  align_vendor_sync_cli_or_die
  _run_adapter_sync
  _prune_deselected_agents
  _prune_deselected_cursor_skills
  _prune_deselected_cursor_generated
  _seed_stack_rule
  _link_claude_skills
  _link_cursor_skills

  _write_or_clear_framework_home
  return 0
}

# Local mode: machine-local absolute path, gitignored.
# Vendor submodule/copy: SSOT is in-repo vendor/agent-collections — never write
# this file, and remove leftovers from older installer versions.
_write_or_clear_framework_home() {
  local home_marker="${TARGET_DIR}/.agent-collections"
  mkdir -p "$home_marker"
  if [[ "${VENDOR_MODE:-}" == "submodule" ]] || [[ "${VENDOR_MODE:-}" == "copy" ]]; then
    rm -f "${home_marker}/framework-home.txt"
    return 0
  fi
  echo "${COLLECTIONS_HOME}" > "${home_marker}/framework-home.txt"
}
