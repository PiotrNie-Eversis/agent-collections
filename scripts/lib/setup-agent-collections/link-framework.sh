#!/usr/bin/env bash
# lib/setup-agent-collections/link-framework.sh — materialise adapters into target (no skills mirror).

readonly STACK_RULE_BASENAME="eversis-project-stack.mdc"

_make_symlink() {
  local src="$1" dst="$2"
  if [[ "$OS_TYPE" == "windows" ]]; then
    cmd //c "mklink /J \"${dst}\" \"${src}\"" 2>/dev/null && return 0
    return 1
  fi
  local rel=""
  local rel_script="${LIB_DIR}/relative-path.mjs"
  if [[ -f "$rel_script" ]] && command -v node >/dev/null 2>&1; then
    rel="$(node "$rel_script" "$(dirname "$dst")" "$src" 2>/dev/null || true)"
  fi
  if [[ -n "$rel" ]] && [[ "$rel" != /* ]]; then
    ln -sfn "$rel" "$dst"
  else
    ln -sfn "$src" "$dst"
  fi
}

_seed_stack_rule() {
  local stack_dst="${TARGET_DIR}/.cursor/rules/${STACK_RULE_BASENAME}"
  mkdir -p "$(dirname "$stack_dst")"
  if [[ -f "$stack_dst" ]]; then
    log_info "eversis-project-stack.mdc already exists — not overwritten (project-owned)."
    return 0
  fi
  local template="${COLLECTIONS_HOME}/templates/eversis-project-stack.example.mdc"
  if [[ ! -f "$template" ]]; then
    template="${COLLECTIONS_HOME}/.cursor/rules/${STACK_RULE_BASENAME}"
  fi
  if [[ -f "$template" ]]; then
    cp "$template" "$stack_dst"
    log_ok "Created ${STACK_RULE_BASENAME} from template — customise for your project."
  else
    log_warn "No stack rule template found — create ${stack_dst} manually."
  fi
}

_prune_deselected_agents() {
  local agents_csv="${SELECTED_AGENTS:-cursor}"
  if echo ",${agents_csv}," | grep -q ',claude,'; then
    return 0
  fi
  local claude_md="${TARGET_DIR}/CLAUDE.md"
  if [[ -f "$claude_md" ]] && grep -q 'GENERATED by adapters/claude/generate.mjs' "$claude_md" 2>/dev/null; then
    rm -f "$claude_md"
    log_ok "Removed generated CLAUDE.md (Claude not in --agents)."
  elif [[ -f "$claude_md" ]]; then
    log_info "CLAUDE.md exists but is not framework-generated — left in place."
  fi
  local claudeignore="${TARGET_DIR}/.claudeignore"
  if [[ -f "$claudeignore" ]] && grep -q 'Agent Collections ignore triad' "$claudeignore" 2>/dev/null; then
    rm -f "$claudeignore"
    log_ok "Removed framework .claudeignore (Claude not in --agents)."
  fi
  local claude_skills="${TARGET_DIR}/.claude/skills"
  if [[ -d "$claude_skills" ]]; then
    # Only the eversis-* entries are framework-owned (linked/copied
    # exclusively by _link_claude_skills) — a consumer may keep unrelated
    # skill packages alongside them, so prune by name, not the whole dir.
    local removed=0
    local entry
    for entry in "$claude_skills"/eversis-*; do
      [[ -e "$entry" ]] || continue
      rm -rf "$entry"
      removed=$((removed + 1))
    done
    if [[ "$removed" -gt 0 ]]; then
      log_ok "Removed ${removed} framework skill package(s) from .claude/skills/ (Claude not in --agents)."
    fi
  fi

  # .claude/commands/ and .claude/rules/ are normally pruned of orphans as a
  # side effect of the Claude generators re-running (cleanupOrphanCommands /
  # cleanupOrphanScopedRules) — but _run_adapter_sync above never invoked
  # those generators at all for this run (claude isn't in --agents), so nothing
  # exercised that cleanup path. Prune them here too, marker-gated exactly
  # like CLAUDE.md/.claudeignore above, so Claude Code stops seeing stale
  # framework slash commands / scoped rules after a deselect.
  _prune_marker_gated_dir "${TARGET_DIR}/.claude/commands" \
    "GENERATED by adapters/claude/generate-commands.mjs" ".claude/commands/*.md"
  _prune_marker_gated_dir "${TARGET_DIR}/.claude/rules" \
    "GENERATED by adapters/claude/generate.mjs" ".claude/rules/*.md"
  # Same for the generated role subagents and the spec artifact hook
  # launcher; consumer-made agents and hooks (no marker) stay.
  _prune_marker_gated_dir "${TARGET_DIR}/.claude/agents" \
    "GENERATED by adapters/claude/generate-agents.mjs" ".claude/agents/*.md"
  _prune_marker_gated_dir "${TARGET_DIR}/.claude/hooks" \
    "GENERATED by adapters/claude/generate-hooks.mjs" ".claude/hooks/*.cjs" \
    "eversis-*.cjs"
  # merge_claude_settings returns early without Claude, so the framework
  # PostToolUse entry (now pointing at a removed launcher) is dropped here;
  # nothing else in .claude/settings.json is touched.
  remove_claude_framework_hook
}

# Independent of _prune_deselected_agents (Claude-scoped): prunes the
# .cursor/skills/ mirror when Cursor is deselected. Only the skills mirror is
# pruned here — .cursor/rules/*.mdc and .cursor/commands/*.md deselect-pruning
# for Cursor was a separate, pre-existing gap (see
# docs/specs/promote-skill-cursor-packaging/promote-skill-cursor-packaging.plan.md
# Open Question 3); it is now closed by _prune_deselected_cursor_generated
# below, which marker-gates those files instead.
_prune_deselected_cursor_skills() {
  local agents_csv="${SELECTED_AGENTS:-cursor}"
  if echo ",${agents_csv}," | grep -q ',cursor,'; then
    return 0
  fi
  local cursor_skills="${TARGET_DIR}/.cursor/skills"
  [[ -d "$cursor_skills" ]] || return 0

  local removed=0
  local entry
  for entry in "$cursor_skills"/eversis-*; do
    [[ -e "$entry" ]] || continue
    rm -rf "$entry"
    removed=$((removed + 1))
  done
  if [[ "$removed" -gt 0 ]]; then
    log_ok "Removed ${removed} framework skill package(s) from .cursor/skills/ (Cursor not in --agents)."
  fi
}

# Cursor deselect (explicit --agents without cursor): remove generated
# .cursor/commands/eversis-*.md and .cursor/rules/eversis-*.mdc. Without this,
# detect_installed_agents (upgrade.sh) finds their markers on the next
# --upgrade and silently re-selects Cursor. Marker-gated:
# the project-owned eversis-project-stack.mdc (no marker) and any hand-written
# eversis-* file stay; the stack rule is also skipped by name for safety.
_prune_deselected_cursor_generated() {
  local agents_csv="${SELECTED_AGENTS:-cursor}"
  if echo ",${agents_csv}," | grep -q ',cursor,'; then
    return 0
  fi
  _prune_marker_gated_dir "${TARGET_DIR}/.cursor/commands" \
    "GENERATED by adapters/cursor/generate.mjs" ".cursor/commands/*.md" \
    "eversis-*.md" "Cursor not in --agents"
  _prune_marker_gated_dir "${TARGET_DIR}/.cursor/rules" \
    "GENERATED by adapters/cursor/generate.mjs" ".cursor/rules/*.mdc" \
    "eversis-*.mdc" "Cursor not in --agents"
}

# Args: dir, marker, label, [glob (default eversis-*.md)],
# [reason for the log line (default "Claude not in --agents")].
# The defaults keep the original Claude call sites unchanged.
_prune_marker_gated_dir() {
  local dir="$1" marker="$2" label="$3"
  local pattern="${4:-eversis-*.md}" reason="${5:-Claude not in --agents}"
  [[ -d "$dir" ]] || return 0
  local removed=0
  local f
  for f in "$dir"/$pattern; do
    [[ -f "$f" ]] || continue
    [[ "$(basename "$f")" == "$STACK_RULE_BASENAME" ]] && continue
    grep -q "$marker" "$f" 2>/dev/null || continue
    rm -f "$f"
    removed=$((removed + 1))
  done
  if [[ "$removed" -gt 0 ]]; then
    log_ok "Removed ${removed} generated ${label} file(s) (${reason})."
  fi
}

_resolve_framework_prefix() {
  # Consumer installs vendor the framework away from TARGET_DIR (or don't
  # vendor it at all), so .ai/... paths hardcoded for self-host (F11) must
  # be rewritten. Self-host (COLLECTIONS_HOME == TARGET_DIR, i.e. this repo)
  # needs no prefix; submodule/copy vendor modes resolve to a real
  # repo-relative path (vendor/agent-collections); local mode has no
  # in-tree path, so fall back to the Claude Code env-var token.
  if [[ "$COLLECTIONS_HOME" == "$TARGET_DIR" ]]; then
    return 0
  fi
  if [[ "${VENDOR_MODE:-}" == "submodule" ]] || [[ "${VENDOR_MODE:-}" == "copy" ]]; then
    local rel_script="${LIB_DIR}/relative-path.mjs"
    local prefix=""
    if [[ -f "$rel_script" ]] && command -v node >/dev/null 2>&1; then
      prefix="$(node "$rel_script" "$TARGET_DIR" "$COLLECTIONS_HOME" 2>/dev/null || true)"
    fi
    if [[ -z "$prefix" ]]; then
      log_warn "Could not compute --framework-prefix for vendored install (relative-path.mjs failed or Node is unavailable) — CLAUDE.md / .claude/commands will fall back to unprefixed .ai/... paths, which will not resolve under ${TARGET_DIR}. Re-run adapter sync after confirming ${COLLECTIONS_HOME} exists."
      return 0
    fi
    echo "$prefix"
    return 0
  fi
  echo '${AGENT_COLLECTIONS_HOME}'
}

# Shared skills mirror for every agent that reads .ai/skills/eversis-* from a
# local <agent>/skills/ folder (Claude, Cursor, Pi). Args: agent id (selection
# guard), destination dir relative to TARGET_DIR (e.g. .claude/skills), and an
# optional glob of destination entries the stale-prune must never touch (Pi
# passes 'eversis-rule-*': those role skills are written by the Pi generator,
# not mirrored from .ai/skills/). Returns non-zero on any failed mkdir / link /
# copy / prune so an isolated caller (run_pi_stage) can report it.
# Optional 4th arg: link mode for this mirror only (symlink | copy). Empty =
# EFFECTIVE_LINK_MODE. Pi passes copy without touching the exported
# EFFECTIVE_LINK_MODE, which the rest of the run and the record still use.
# Optional 5th arg: "backup" (Pi only) copies each entry that is neither an identical framework copy
# nor the installer's own recorded copy aside
# (_backup_hand_made_pi_skill) before it is replaced or stale-pruned. Claude and
# Cursor never pass it, so their mirrors behave as before.
# In "backup" mode the names copied by this call are also collected in
# PI_MIRROR_COPIED_NAMES (space-separated string) for the Pi skills manifest.
# Every call clears that variable first, before any early return, so it only
# ever holds names copied by the latest call.
_link_agent_skills() {
  local agent="$1" dst_rel="$2" prune_exclude="${3:-}"
  local mode="${4:-${EFFECTIVE_LINK_MODE:-symlink}}"
  local backup="${5:-}"
  PI_MIRROR_COPIED_NAMES=""
  if ! echo ",${SELECTED_AGENTS:-}," | grep -q ",${agent},"; then
    return 0
  fi
  local skills_src_root="${COLLECTIONS_HOME}/.ai/skills"
  [[ -d "$skills_src_root" ]] || return 0

  local skills_dst_root="${TARGET_DIR}/${dst_rel}"
  mkdir -p "$skills_dst_root" || return 1

  local src name dst count=0 fallbacks=0
  local keep_names=""
  for src in "$skills_src_root"/eversis-*; do
    [[ -d "$src" ]] || continue
    name="$(basename "$src")"
    keep_names="${keep_names},${name},"
    dst="${skills_dst_root}/${name}"
    if [[ "$backup" == "backup" ]]; then
      _backup_hand_made_pi_skill "$dst" || return 1
    fi
    rm -rf "$dst" || return 1
    if [[ "$mode" == "symlink" ]]; then
      # A link can fail where the recorded mode says symlink (for example a
      # Windows junction refused by policy). Copy that one entry instead of
      # stopping half-way with the entry already removed above; the rest of
      # the mirror keeps the requested mode.
      if ! _make_symlink "$src" "$dst"; then
        log_warn "Link failed for ${name} — copied instead"
        rm -rf "$dst" || return 1
        cp -R "$src" "$dst" || return 1
        fallbacks=$((fallbacks + 1))
      fi
    else
      cp -R "$src" "$dst" || return 1
    fi
    if [[ "$backup" == "backup" ]]; then
      PI_MIRROR_COPIED_NAMES="${PI_MIRROR_COPIED_NAMES:+${PI_MIRROR_COPIED_NAMES} }${name}"
    fi
    count=$((count + 1))
  done
  if [[ "$fallbacks" -gt 0 ]]; then
    log_ok "Linked ${count} skill package(s) into ${dst_rel}/ (mode: ${mode}; ${fallbacks} copied after a failed link)."
  else
    log_ok "Linked ${count} skill package(s) into ${dst_rel}/ (mode: ${mode})."
  fi

  # A skill package renamed or removed upstream (in .ai/skills/) would
  # otherwise survive forever in <agent>/skills/ — the loop above only adds
  # entries for what exists in the source today, it never removes what no
  # longer does. Prune destination entries with no matching source name.
  local existing removed=0
  for existing in "$skills_dst_root"/eversis-*; do
    [[ -e "$existing" ]] || continue
    name="$(basename "$existing")"
    case "$keep_names" in
      *",${name},"*) continue ;;
    esac
    # shellcheck disable=SC2254
    if [[ -n "$prune_exclude" ]]; then
      case "$name" in
        $prune_exclude) continue ;;
      esac
    fi
    if [[ "$backup" == "backup" ]]; then
      _backup_hand_made_pi_skill "$existing" || return 1
    fi
    rm -rf "$existing" || return 1
    removed=$((removed + 1))
  done
  if [[ "$removed" -gt 0 ]]; then
    log_ok "Removed ${removed} stale skill package(s) from ${dst_rel}/ (no longer in .ai/skills/)."
  fi
  return 0
}

_link_claude_skills() {
  _link_agent_skills claude .claude/skills
}

# Same staleness concern as _link_claude_skills — prune destination entries
# with no matching source name (handled inside _link_agent_skills).
_link_cursor_skills() {
  _link_agent_skills cursor .cursor/skills
}

# Completeness check for one skills mirror. Args: agent id (used in the
# message only — the caller decides which mirrors to check), destination dir
# relative to TARGET_DIR (e.g. .claude/skills). Every .ai/skills/eversis-*
# package must have a readable <dst_rel>/<name>/SKILL.md. Checking SKILL.md
# rather than the entry itself also catches a dangling link and a symlink
# checked out as a plain text file (Git on Windows without symlink support).
# Read-only. On any miss, prints the missing names with a recovery hint and
# returns 1; returns 0 when the mirror is complete or there is no source tree.
_verify_skills_mirror() {
  local agent="$1" dst_rel="$2"
  local skills_src_root="${COLLECTIONS_HOME}/.ai/skills"
  [[ -d "$skills_src_root" ]] || return 0

  local src name total=0
  local -a missing=()
  for src in "$skills_src_root"/eversis-*; do
    [[ -d "$src" ]] || continue
    name="$(basename "$src")"
    total=$((total + 1))
    if [[ ! -f "${TARGET_DIR}/${dst_rel}/${name}/SKILL.md" ]] \
      || [[ ! -r "${TARGET_DIR}/${dst_rel}/${name}/SKILL.md" ]]; then
      missing+=("$name")
    fi
  done

  if [[ ${#missing[@]} -gt 0 ]]; then
    log_error "${agent} skills mirror ${dst_rel}/ is incomplete: ${#missing[@]} of ${total} skill package(s) have no readable SKILL.md:"
    for name in "${missing[@]}"; do
      echo "  missing: ${dst_rel}/${name}/SKILL.md" >&2
    done
    log_error "Fix: re-run with --link-mode copy (for example: --upgrade --sync --link-mode copy)."
    return 1
  fi
  log_ok "Verified ${total} skill package(s) in ${dst_rel}/ (${agent})."
  return 0
}

# Prints the agents CSV in $1 without the pi id (order kept, empty ids dropped).
_agents_without_pi() {
  local csv="$1" out="" id
  local -a ids=()
  IFS=',' read -ra ids <<< "$csv"
  for id in ${ids[@]+"${ids[@]}"}; do
    id="${id// /}"
    [[ -z "$id" || "$id" == "pi" ]] && continue
    out="${out:+${out},}${id}"
  done
  printf '%s' "$out"
}

_pi_selected() {
  echo ",${SELECTED_AGENTS:-}," | grep -q ',pi,'
}

# True when pi is selected and no other agent is (Pi-only install).
_pi_only_selected() {
  _pi_selected && [[ -z "$(_agents_without_pi "${SELECTED_AGENTS:-}")" ]]
}

_run_adapter_sync() {
  require_cmd node "Install Node.js 22 or newer from https://nodejs.org"
  local sync_mjs="${COLLECTIONS_HOME}/adapters/sync.mjs"
  [[ -f "$sync_mjs" ]] || die "Missing adapters/sync.mjs in framework home."

  local agents_csv="${SELECTED_AGENTS:-cursor}"
  # Pi runs in its own isolated stage (run_pi_stage) so a Pi failure never
  # aborts the other agents. Pass only the non-Pi agents here; a Pi-only
  # selection skips this sync entirely — never fall back to cursor and never
  # call sync.mjs with an empty --agents.
  agents_csv="$(_agents_without_pi "$agents_csv")"
  if [[ -z "$agents_csv" ]]; then
    log_info "Adapter sync for Cursor / Claude skipped (only pi selected — handled by the Pi stage)."
    return 0
  fi
  local args=(--out "${TARGET_DIR}" --agents "${agents_csv}")

  local framework_prefix
  framework_prefix="$(_resolve_framework_prefix)"
  if [[ -n "$framework_prefix" ]]; then
    args+=(--framework-prefix "$framework_prefix")
  fi

  log_info "Running adapter sync → ${TARGET_DIR} (agents: ${agents_csv}) …"
  (cd "$COLLECTIONS_HOME" && node "$sync_mjs" "${args[@]}") \
    || die "adapters/sync.mjs failed."
  log_ok "Adapter sync complete."
}

link_framework_files() {
  local link_mode="${ARG_LINK_MODE:-auto}"
  if [[ "$link_mode" == "auto" ]]; then
    if [[ "$OS_TYPE" == "windows" ]]; then
      link_mode="copy"
    else
      link_mode="symlink"
    fi
  fi
  EFFECTIVE_LINK_MODE="$link_mode"
  export EFFECTIVE_LINK_MODE

  mkdir -p "${TARGET_DIR}/.cursor/rules"

  # Skills are mirrored into <agent>/skills/ for both Claude and Cursor
  # (docs/specs/promote-skill-cursor-packaging/) — a real local fallback file,
  # not a vendor-specific "Agent Skills" UI registration. Prompts/commands are
  # NOT mirrored as a second copy: .cursor/commands/*.md is the generated
  # adapter output itself (adapters/cursor/generate.mjs, with a vendor-path-
  # corrected SSOT pointer via --framework-prefix), so no separate mirror step
  # is needed for those.
  # Align a clean submodule pin to INSTALLER_FRAMEWORK_HOME when vendored
  # sync.mjs would reject flags this launched installer will pass.
  align_vendor_sync_cli_or_die
  _run_adapter_sync
  _prune_deselected_agents
  _prune_deselected_cursor_skills
  _prune_deselected_cursor_generated
  _seed_stack_rule
  # This function runs inside `link_framework_files || { … }`, where set -e
  # is off, so every mirror step checks its own return value: a failed
  # mirror must fail the run, not leave an empty <agent>/skills/ behind.
  _link_claude_skills || return 1
  _link_cursor_skills || return 1

  _write_or_clear_framework_home

  # Completeness check after every install, --upgrade and --sync, for the
  # mirrors of the selected agents (deselected mirrors were pruned above).
  if echo ",${SELECTED_AGENTS:-}," | grep -q ',claude,'; then
    _verify_skills_mirror claude .claude/skills || return 1
  fi
  if echo ",${SELECTED_AGENTS:-}," | grep -q ',cursor,'; then
    _verify_skills_mirror cursor .cursor/skills || return 1
  fi
  return 0
}

# Local mode: machine-local absolute path, gitignored.
# Vendor submodule/copy: SSOT is in-repo vendor/agent-collections — never write
# this file, and remove leftovers from older installer versions.
_write_or_clear_framework_home() {
  local home_marker="${TARGET_DIR}/.agent-collections"
  mkdir -p "$home_marker"
  if [[ "${VENDOR_MODE:-}" == "submodule" ]] || [[ "${VENDOR_MODE:-}" == "copy" ]]; then
    rm -f "${home_marker}/framework-home.txt"
    return 0
  fi
  echo "${COLLECTIONS_HOME}" > "${home_marker}/framework-home.txt"
}

# ---------------------------------------------------------------------------
# Pi stage — everything Pi-specific (generation, skills mirror,
# deselect pruning; the .pi/mcp.json merge lives in mcp-merge.sh) runs
# isolated from the other agents. A Pi failure sets PI_STAGE_FAILED=true and
# PI_STAGE_FAILURE_REASON and records a "pi" failure; it never edits
# SELECTED_AGENTS, because an empty list falls back to cursor across the
# installer (${SELECTED_AGENTS:-cursor}). The caller decides what happens
# next: Pi-only → exit 1 right away; otherwise continue and exit 1 at the end.
# ---------------------------------------------------------------------------

readonly PI_GENERATED_MARKER="GENERATED by adapters/pi/generate.mjs"

# Hand-made .pi/skills/eversis-* entries are copied here before the installer
# removes or replaces them. Outside .pi/skills/, so Pi never loads a
# backup as a skill; legacy-pi.sh skips it when it looks for a hand port.
readonly PI_SKILL_BACKUP_REL=".pi/pre-agent-collections-backup/skills"

# Content hash of each .pi/skills/ entry the installer copied (written by
# pi-skills-manifest.mjs after the Pi mirror copy). An entry that still matches
# its recorded hash is the installer's own outdated copy and is replaced or
# removed without a backup. It lives outside .pi/, so no Pi version can load
# it as a skill or a resource, and next to install-selection.json, whose
# content also depends only on the framework version.
readonly PI_SKILLS_MANIFEST_REL=".agent-collections/pi-skills-mirror.json"

# Start from "false" so a stray value in the caller's env never marks a run
# as a Pi failure.
PI_STAGE_FAILED="false"
PI_STAGE_FAILURE_REASON=""
# Start empty for the same reason: a value from the caller's env must never
# reach the manifest. _link_agent_skills also clears it on every call.
PI_MIRROR_COPIED_NAMES=""

# Args: reason. Records the first Pi failure (later calls keep the first cause).
mark_pi_stage_failed() {
  local reason="$1"
  if [[ "${PI_STAGE_FAILED:-false}" != "true" ]]; then
    PI_STAGE_FAILED="true"
    PI_STAGE_FAILURE_REASON="$reason"
    if declare -F record_fail >/dev/null 2>&1; then
      record_fail "pi"
    fi
  fi
  export PI_STAGE_FAILED PI_STAGE_FAILURE_REASON
  log_error "pi: ${reason} — other agents' output is kept; pi is left out of the recorded selection."
}

# Same framework prefix handling as _run_adapter_sync, but --agents pi only and
# a non-zero return instead of die. The first "error:" line of the generator
# output becomes the failure reason.
_run_pi_adapter_sync() {
  local sync_mjs="${COLLECTIONS_HOME}/adapters/sync.mjs"
  if ! command -v node >/dev/null 2>&1; then
    PI_SYNC_ERROR="node not found (install Node.js 22 or newer)"
    return 1
  fi
  if [[ ! -f "$sync_mjs" ]]; then
    PI_SYNC_ERROR="missing adapters/sync.mjs in framework home"
    return 1
  fi

  local args=(--out "${TARGET_DIR}" --agents pi)
  local framework_prefix
  framework_prefix="$(_resolve_framework_prefix)"
  if [[ -n "$framework_prefix" ]]; then
    args+=(--framework-prefix "$framework_prefix")
  fi

  log_info "Running Pi adapter sync → ${TARGET_DIR} (agents: pi) …"
  local output="" rc=0
  output="$(cd "$COLLECTIONS_HOME" && node "$sync_mjs" "${args[@]}" 2>&1)" || rc=$?
  [[ -n "$output" ]] && printf '%s\n' "$output"
  if [[ "$rc" -ne 0 ]]; then
    PI_SYNC_ERROR="$(printf '%s\n' "$output" | grep -m1 '^error:' | sed 's/^error: *//')"
    [[ -n "$PI_SYNC_ERROR" ]] || PI_SYNC_ERROR="adapters/sync.mjs --agents pi exited with code ${rc}"
    return 1
  fi
  log_ok "Pi adapter sync complete."
  return 0
}

# Pi deselect (pi not in --agents): remove only framework-generated Pi files.
# Marker-gated for generated files; eversis-* mirror entries in .pi/skills/
# are framework-owned by name (same rule as .claude/skills/), and so is
# .pi/eversis-state/, which the process-rules extension creates and which has no
# marker. Consumer-owned .pi/settings.json and .pi/mcp.json stay (same convention
# as .mcp.json / .cursor/mcp.json on deselect). The Pi skills manifest
# (PI_SKILLS_MANIFEST_REL) is removed after the mirror entries, because their
# backup check still reads it, and also when .pi/ no longer exists. Returns
# non-zero when a removal fails.
_prune_deselected_pi() {
  local pi_dir="${TARGET_DIR}/.pi"
  if [[ ! -d "$pi_dir" ]]; then
    _remove_pi_skills_manifest
    return
  fi
  local reason="Pi not in --agents"

  local append_system="${pi_dir}/APPEND_SYSTEM.md"
  if [[ -f "$append_system" ]] && grep -qF "$PI_GENERATED_MARKER" "$append_system" 2>/dev/null; then
    rm -f "$append_system" || return 1
    log_ok "Removed generated .pi/APPEND_SYSTEM.md (${reason})."
  fi

  local extension_name extension
  for extension_name in eversis-context-budget.ts eversis-process-rules.ts eversis-review.ts; do
    extension="${pi_dir}/extensions/${extension_name}"
    if [[ -f "$extension" ]] && grep -qF "$PI_GENERATED_MARKER" "$extension" 2>/dev/null; then
      rm -f "$extension" || return 1
      log_ok "Removed generated .pi/extensions/${extension_name} (${reason})."
    fi
  done

  local state_dir="${pi_dir}/eversis-state"
  if [[ -e "$state_dir" ]] || [[ -L "$state_dir" ]]; then
    rm -rf "$state_dir" || return 1
    log_ok "Removed .pi/eversis-state/ (${reason})."
  fi

  _prune_marker_gated_dir "${pi_dir}/prompts" "$PI_GENERATED_MARKER" \
    ".pi/prompts/*.md" "eversis-*.md" "$reason"
  _log_pi_deselect_leftovers

  local skills_dir="${pi_dir}/skills"
  if [[ -d "$skills_dir" ]]; then
    local entry name removed_roles=0 removed_mirror=0
    for entry in "$skills_dir"/eversis-*; do
      [[ -e "$entry" ]] || [[ -L "$entry" ]] || continue
      name="$(basename "$entry")"
      case "$name" in
        eversis-rule-*)
          # Generated role skills: only when their SKILL.md carries the marker.
          [[ -f "${entry}/SKILL.md" ]] || continue
          grep -qF "$PI_GENERATED_MARKER" "${entry}/SKILL.md" 2>/dev/null || continue
          rm -rf "$entry" || return 1
          removed_roles=$((removed_roles + 1))
          ;;
        *)
          # An entry that is neither an identical framework copy nor the
          # installer's own recorded copy is copied aside first.
          _backup_hand_made_pi_skill "$entry" || return 1
          rm -rf "$entry" || return 1
          removed_mirror=$((removed_mirror + 1))
          ;;
      esac
    done
    if [[ "$removed_roles" -gt 0 ]]; then
      log_ok "Removed ${removed_roles} generated role skill(s) from .pi/skills/ (${reason})."
    fi
    if [[ "$removed_mirror" -gt 0 ]]; then
      log_ok "Removed ${removed_mirror} framework skill package(s) from .pi/skills/ (${reason})."
    fi
  fi
  _remove_pi_skills_manifest || return 1
  return 0
}

# Removes the Pi skills manifest when present (no message when it was absent).
# Returns non-zero when the removal fails.
_remove_pi_skills_manifest() {
  local manifest="${TARGET_DIR}/${PI_SKILLS_MANIFEST_REL}"
  if [[ -e "$manifest" ]] || [[ -L "$manifest" ]]; then
    rm -f "$manifest" || return 1
  fi
  return 0
}

# Writes the Pi skills manifest from the names the latest Pi mirror call
# copied (PI_MIRROR_COPIED_NAMES), so it follows both the copy loop and the
# stale prune. A failed write is a warning, not a Pi stage failure: the only
# cost is an extra backup of framework copies on the next upgrade.
_write_pi_skills_manifest() {
  local helper="${LIB_DIR:-}/pi-skills-manifest.mjs"
  local manifest="${TARGET_DIR}/${PI_SKILLS_MANIFEST_REL}"
  local -a names=()
  read -ra names <<< "${PI_MIRROR_COPIED_NAMES:-}"
  if [[ -n "${LIB_DIR:-}" ]] && [[ -f "$helper" ]] && command -v node >/dev/null 2>&1 \
    && node "$helper" write "$manifest" "${TARGET_DIR}/.pi/skills" ${names[@]+"${names[@]}"} >/dev/null 2>&1; then
    return 0
  fi
  log_warn "Could not write ${PI_SKILLS_MANIFEST_REL} — the next upgrade may back up framework copies in .pi/skills/ again."
  return 0
}

# True when the entry at $2 still matches the hash the installer recorded for
# skill name $1 in the Pi skills manifest. Fails closed: a missing helper,
# manifest or node, an invalid manifest, a missing name or a hash failure all
# count as no match, which keeps the backup.
_pi_skill_matches_manifest() {
  local name="$1" entry="$2"
  local helper="${LIB_DIR:-}/pi-skills-manifest.mjs"
  local manifest="${TARGET_DIR}/${PI_SKILLS_MANIFEST_REL}"
  [[ -n "${LIB_DIR:-}" ]] && [[ -f "$helper" ]] && [[ -f "$manifest" ]] || return 1
  command -v node >/dev/null 2>&1 || return 1
  node "$helper" match "$manifest" "$name" "$entry" >/dev/null 2>&1
}

# A .pi/skills/eversis-* mirror entry is framework-owned by name, but a
# hand-ported Pi setup (or a person) may have put its own skill — a folder or a
# single file such as eversis-notes.md — under that name. Before the entry at
# $1 is removed or replaced, copy it to .pi/pre-agent-collections-backup/skills/
# unless it is an identical framework copy or the installer's own recorded
# copy: a non-symlink directory or regular
# file (a symlink points at the framework and holds nothing to lose) with no
# counterpart in ${COLLECTIONS_HOME}/.ai/skills/<name>, or one that differs from
# it (a file never matches a framework directory), is backed up unless its
# content still equals the hash recorded for <name> in the Pi skills manifest
# (PI_SKILLS_MANIFEST_REL). Such an entry is the installer's own outdated
# copy from an earlier release, so it is replaced or removed with no backup
# and no warning. Without a manifest, or without a matching entry in it, an
# outdated framework copy also differs, so it is backed up too and the warning
# says only which case applies, not who made it. Same convention as the Pi generator's
# .pre-agent-collections.bak: an identical existing backup is reused, otherwise
# a timestamped name is used so an older backup is never overwritten. Returns
# non-zero when the copy fails, so the caller keeps the entry. eversis-rule-*
# role skills are the generator's.
_backup_hand_made_pi_skill() {
  local entry="$1" name
  [[ ! -L "$entry" ]] || return 0
  [[ -d "$entry" ]] || [[ -f "$entry" ]] || return 0
  name="$(basename "$entry")"
  case "$name" in
    eversis-rule-*) return 0 ;;
  esac
  local src="${COLLECTIONS_HOME}/.ai/skills/${name}" reason
  if [[ -e "$src" ]]; then
    _pi_same_entry "$src" "$entry" && return 0
    reason="differs from the framework skill"
  else
    reason="no matching framework skill"
  fi
  _pi_skill_matches_manifest "$name" "$entry" && return 0

  local backup_root="${TARGET_DIR}/${PI_SKILL_BACKUP_REL}"
  mkdir -p "$backup_root" || return 1
  local dst="${backup_root}/${name}"
  if [[ -e "$dst" ]] && ! _pi_same_entry "$dst" "$entry"; then
    local stamp n=2
    stamp="$(date +%Y%m%dT%H%M%S)"
    dst="${backup_root}/${name}.${stamp}"
    while [[ -e "$dst" ]] && ! _pi_same_entry "$dst" "$entry"; do
      dst="${backup_root}/${name}.${stamp}-${n}"
      n=$((n + 1))
    done
  fi
  if [[ ! -e "$dst" ]]; then
    cp -R "$entry" "$dst" || return 1
  fi
  log_warn "Backed up .pi/skills/${name} to ${PI_SKILL_BACKUP_REL}/$(basename "$dst") (${reason})."
  return 0
}

# True when $1 and $2 are both regular files with the same bytes, or both
# directories with the same tree. A file and a directory never match.
_pi_same_entry() {
  local a="$1" b="$2"
  if [[ -f "$a" ]] && [[ -f "$b" ]]; then
    cmp -s "$a" "$b"
  elif [[ -d "$a" ]] && [[ -d "$b" ]]; then
    diff -rq "$a" "$b" >/dev/null 2>&1
  else
    return 1
  fi
}

# After a deselect, unmarked .pi/prompts/eversis-*.md (and files that
# still carry the legacy hand-port marker) stay — they are not framework files.
# They are also what makes the next --upgrade / --sync without --agents stop
# (check_pi_hand_port_or_stop), so name them for the person to delete.
_log_pi_deselect_leftovers() {
  local pi_dir="${TARGET_DIR}/.pi" f left=""
  for f in "${pi_dir}/prompts"/eversis-*.md; do
    [[ -f "$f" ]] || continue
    grep -qF "$PI_GENERATED_MARKER" "$f" 2>/dev/null && continue
    left="${left}
  .pi/prompts/$(basename "$f")"
  done
  if declare -F _legacy_pi_marked_files >/dev/null 2>&1; then
    local legacy
    while IFS= read -r legacy; do
      [[ -n "$legacy" ]] || continue
      case "$left" in
        *"
  ${legacy}"*) continue ;;
      esac
      left="${left}
  ${legacy}"
    done <<< "$(_legacy_pi_marked_files)"
  fi
  if [[ -n "$left" ]]; then
    log_info "Left in place (not framework-generated; delete them if Pi is no longer used, or a later --upgrade without --agents stops):${left}"
  fi
  return 0
}

# Isolated Pi stage, called by setup-agent-collections.sh after
# link_framework_files. Returns 1 when the Pi stage failed (flag + reason set,
# "pi" failure recorded); never dies for a Pi-caused error. Every sub-step is
# checked explicitly because set -e is inactive inside `… || …` callers.
run_pi_stage() {
  if ! _pi_selected; then
    if ! _prune_deselected_pi; then
      mark_pi_stage_failed "could not remove generated .pi/ files after deselecting Pi"
      return 1
    fi
    return 0
  fi

  if [[ -z "${EFFECTIVE_LINK_MODE:-}" ]]; then
    EFFECTIVE_LINK_MODE="symlink"
    [[ "${OS_TYPE:-}" == "windows" ]] && EFFECTIVE_LINK_MODE="copy"
    export EFFECTIVE_LINK_MODE
  fi

  PI_SYNC_ERROR=""
  if ! _run_pi_adapter_sync; then
    mark_pi_stage_failed "Pi adapter generation failed: ${PI_SYNC_ERROR}"
    return 1
  fi
  # The Pi mirror is always a copy, whatever --link-mode says. A tool
  # that writes .pi/skills/eversis-*/ (e.g. a legacy consumer Pi generator)
  # would otherwise write through a symlink into vendor/agent-collections/ or
  # the shared framework checkout. Existing symlinked entries are replaced
  # (rm -rf removes the link, not its target).
  # Hand-made entries under a mirror name are backed up first.
  if ! _link_agent_skills pi .pi/skills 'eversis-rule-*' copy backup; then
    mark_pi_stage_failed "framework skills mirror into .pi/skills/ failed"
    return 1
  fi
  # Only after a successful mirror (copy loop and stale prune): record what
  # this call copied, so the next upgrade recognises the installer's own
  # copies. A Pi stage that failed above keeps the old manifest as it is.
  _write_pi_skills_manifest
  return 0
}
